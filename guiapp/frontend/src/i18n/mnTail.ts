type MnTailTemplate = {
    re: RegExp;
    literals: number;
    mnParts: string[];
};

let mnTailTemplates: MnTailTemplate[] | null = null;

function splitHoles(input: string): string[] | null {
    const parts: string[] = [];
    let literal = '';
    let holes = 0;
    for (let i = 0; i < input.length; i++) {
        if (input.startsWith('${', i)) {
            let depth = 1;
            let j = i + 2;
            while (j < input.length && depth > 0) {
                if (input.startsWith('${', j)) {
                    depth += 1;
                    j += 2;
                    continue;
                }
                if (input[j] === '}') depth -= 1;
                if (depth === 0) break;
                j += 1;
            }
            if (depth !== 0) return null;
            parts.push(literal);
            literal = '';
            holes += 1;
            i = j;
            continue;
        }
        literal += input[i];
    }
    parts.push(literal);
    return holes > 0 ? parts : null;
}

function escapeLiteral(value: string): string {
    return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function compiledTemplates(): MnTailTemplate[] {
    if (mnTailTemplates) return mnTailTemplates;
    const compiled: MnTailTemplate[] = [];
    for (const key of Object.keys(mnTail)) {
        const parts = splitHoles(key);
        if (!parts) continue;
        const mnParts = splitHoles(mnTail[key]);
        if (!mnParts || mnParts.length !== parts.length) continue;
        const body = parts.map(escapeLiteral).join('([\\s\\S]*?)');
        compiled.push({
            re: new RegExp(`^${body}$`),
            literals: parts.reduce((sum, part) => sum + part.length, 0),
            mnParts,
        });
    }
    compiled.sort((a, b) => b.literals - a.literals);
    mnTailTemplates = compiled;
    return compiled;
}

function fromTemplate(en: string): string {
    let best: { score: number; out: string } | undefined;
    for (const template of compiledTemplates()) {
        if (best && template.literals < best.score) break;
        const match = template.re.exec(en);
        if (!match) continue;
        let out = template.mnParts[0];
        for (let i = 1; i < template.mnParts.length; i++) out += (match[i] ?? '') + template.mnParts[i];
        best = { score: template.literals, out };
        break;
    }
    return best?.out || '';
}

export function tailText(lang: string | undefined | null, en: string, zhHans: string, zhHant?: string): string {
    if (normalizeLang(lang) === 'mn') {
        const exact = mnTail[en];
        if (exact) return exact;
        const templated = fromTemplate(en);
        if (templated) return templated;
        return localizeText(lang, en, zhHans, zhHant);
    }
    return localizeText(lang, en, zhHans, zhHant);
}
