type SurfaceTemplate = {
    re: RegExp;
    literals: number;
    mnParts: string[];
};

let surfaceTemplates: SurfaceTemplate[] | null = null;

function splitSurfaceHoles(input: string): string[] | null {
    const parts: string[] = [];
    let literal = '';
    let holes = 0;
    for (let i = 0; i < input.length; i++) {
        if (input.startsWith('${', i)) {
            let depth = 1;
            let j = i + 2;
            while (j < input.length && depth > 0) {
                if (input.startsWith('${', j)) {
                    depth += 1;
                    j += 2;
                    continue;
                }
                if (input[j] === '}') depth -= 1;
                if (depth === 0) break;
                j += 1;
            }
            if (depth !== 0) return null;
            parts.push(literal);
            literal = '';
            holes += 1;
            i = j;
            continue;
        }
        literal += input[i];
    }
    parts.push(literal);
    return holes > 0 ? parts : null;
}

function escapeSurfaceLiteral(value: string): string {
    return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function compiledSurfaceTemplates(): SurfaceTemplate[] {
    if (surfaceTemplates) return surfaceTemplates;
    const compiled: SurfaceTemplate[] = [];
    for (const key of Object.keys(MN_SURFACE)) {
        const parts = splitSurfaceHoles(key);
        if (!parts) continue;
        const mnParts = splitSurfaceHoles(MN_SURFACE[key]);
        if (!mnParts || mnParts.length !== parts.length) continue;
        const body = parts.map(escapeSurfaceLiteral).join('([\\s\\S]*?)');
        compiled.push({
            re: new RegExp(`^${body}$`),
            literals: parts.reduce((sum, part) => sum + part.length, 0),
            mnParts,
        });
    }
    compiled.sort((a, b) => b.literals - a.literals);
    surfaceTemplates = compiled;
    return compiled;
}

function mnFromSurface(en: string): string | undefined {
    const exact = MN_SURFACE[en];
    if (exact !== undefined && !exact.includes('${')) return exact;
    let best: { score: number; out: string } | undefined;
    for (const template of compiledSurfaceTemplates()) {
        if (best && template.literals < best.score) break;
        const match = template.re.exec(en);
        if (!match) continue;
        let out = template.mnParts[0];
        for (let i = 1; i < template.mnParts.length; i++) out += (match[i] ?? '') + template.mnParts[i];
        best = { score: template.literals, out };
        break;
    }
    return best?.out;
}

export function surfaceText(lang: string, en: string, zhHans: string, zhHant?: string): string {
    if (normalizeLang(lang) === 'mn') {
        const mapped = mnFromSurface(en);
        if (mapped) return mapped;
        return localizeText(lang, en, zhHans, zhHant);
    }
    return localizeText(lang, en, zhHans, zhHant);
}
