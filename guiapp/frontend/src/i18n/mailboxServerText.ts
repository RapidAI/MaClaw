const patternedMn: Array<{ re: RegExp; mn: (parts: string[]) => string }> = [
    { re: /^没有名为「([\s\S]*?)」的邮箱$/, mn: (p) => `«${p[1]}» нэртэй имэйл алга` },
    { re: /^邮箱「([\s\S]*?)」已停用$/, mn: (p) => `«${p[1]}» имэйл түр зогссон` },
    { re: /^邮箱「([\s\S]*?)」没有配置收件$/, mn: (p) => `«${p[1]}» имэйлд хүлээн авалт тохируулаагүй` },
    { re: /^邮箱「([\s\S]*?)」没有配置发件$/, mn: (p) => `«${p[1]}» имэйлд илгээлт тохируулаагүй` },
    { re: /^已经有名为「([\s\S]*?)」的邮箱$/, mn: (p) => `«${p[1]}» нэртэй имэйл аль хэдийн байна` },
    { re: /^邮箱「([\s\S]*?)」指定的签名不存在$/, mn: (p) => `«${p[1]}» имэйлийн заасан гарын үсэг алга` },
    { re: /^一次最多处理 (\d+) 封邮件$/, mn: (p) => `Нэг удаад хамгийн ихдээ ${p[1]} захидал боловсруулна` },
    { re: /^一次最多删除 (\d+) 封邮件$/, mn: (p) => `Нэг удаад хамгийн ихдээ ${p[1]} захидал устгана` },
    // app_mailbox_oauth.go: "%s 邮箱 %s 已登录" with label Gmail or Hotmail.
    { re: /^(Gmail|Hotmail) 邮箱 (\S+) 已登录$/, mn: (p) => `${p[1]} имэйл ${p[2]} нэвтэрсэн` },
];

export function localizeMailboxServerText(lang: string | undefined | null, text: string): string {
    if (normalizeLang(lang) !== 'mn') return text;
    const exact = exactMn[text];
    if (exact) return exact;
    for (const pattern of patternedMn) {
        const match = pattern.re.exec(text);
        if (match) return pattern.mn(match);
    }
    return text;
}
