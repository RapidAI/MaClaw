func (h *IMMessageHandler) applyWorkflowReviewIntent(engine *v2.WorkflowEngine, userID string, intent v2.ReviewIntent, feedback, platform string) *IMAgentResponse {
	if intent == v2.ReviewIntentConfirm && h.shouldRegenerateInvalidCodingTaskBreakdown(engine, userID) {
		log.Printf("[workflow-review] blocking confirm for invalid coding task breakdown: user=%s", userID)
		intent = v2.ReviewIntentSupplement
		feedback = invalidCodingTaskBreakdownFeedbackText()
	}

	// Use V2 StateMachine directly for review intent processing.
	wf := h.getWorkflowV2()
	if wf != nil && wf.machine != nil && wf.machine.GetActive(userID) != nil {
		hr, err := wf.machine.ApplyReviewIntent(userID, string(intent), feedback)
		if err != nil {
			log.Printf("[workflow-review] V2 ApplyReviewIntent error: user=%s intent=%s err=%v", userID, intent, err)
			return h.reviewBarrierResponse(engine, userID)
		}
		h.recordWorkflowReviewFeedbackExperience(userID, intent, feedback)
		if intent == v2.ReviewIntentSwitchTask {
			return h.handleWorkflowInterception(userID, feedback, platform)
		}
		if hr == nil {
			return nil
		}
		// Map HandleResult to WorkflowResponse for existing handler.
		resp := mapHandleResultToWorkflowResponse(hr)
		return h.handleWorkflowEngineResponse(engine, userID, resp, platform)
	}

	// Fallback: engine stub (returns nil, nil).
	resp, err := engine.ApplyReviewIntent(userID, intent, feedback)
	if err != nil {
		log.Printf("[workflow-review] ApplyReviewIntent error: user=%s intent=%s err=%v", userID, intent, err)
		return h.reviewBarrierResponse(engine, userID)
	}
	h.recordWorkflowReviewFeedbackExperience(userID, intent, feedback)
	if intent == v2.ReviewIntentSwitchTask {
		return h.handleWorkflowInterception(userID, feedback, platform)
	}
	return h.handleWorkflowEngineResponse(engine, userID, resp, platform)
}

// mapHandleResultToWorkflowResponse converts a V2 HandleResult to the WorkflowResponse
// format that handleWorkflowEngineResponse expects.
func mapHandleResultToWorkflowResponse(hr *v2.HandleResult) *v2.WorkflowResponse {
	if hr == nil {
		return nil
	}
	resp := &v2.WorkflowResponse{}
	switch hr.Action {
	case v2.ActionRunPhase, v2.ActionModify:
		resp.RunAgentLoop = true
		if hr.Phase != nil {
			resp.PhasePrompt = v2.BuildPhasePrompt(hr.State)
		}
		if hr.ModifyHint != "" {
			resp.PhasePrompt += "\n\nUser modification request: " + hr.ModifyHint
		}
	case v2.ActionConfirmed:
		// Phase advanced — check if next phase needs agent loop.
		if hr.State != nil && hr.State.Status == v2.StatusCompleted {
			resp.Complete = true
		} else {
			resp.Advance = true
			resp.RunAgentLoop = true
			resp.PhasePrompt = v2.BuildPhasePrompt(hr.State)
		}
	case v2.ActionShowForm:
		resp.ShowForm = true
		if hr.Phase != nil && hr.Phase.InputSchema != nil {
			resp.FormSchema = v2MapPhaseInputSchema(hr.Phase.InputSchema)
		}
	case v2.ActionCancelled, v2.ActionCancelAndExecute:
		// Caller handles these before reaching here.
	}
	return resp
}

// v2MapPhaseInputSchema converts V2 PhaseInputSchema to PhaseInputSchemaSpec.
func v2MapPhaseInputSchema(schema *v2.PhaseInputSchema) *v2.PhaseInputSchemaSpec {
	if schema == nil {
		return nil
	}
	spec := &v2.PhaseInputSchemaSpec{
		Title:       schema.Title,
		Description: schema.Description,
	}
	for _, f := range schema.Fields {
		field := v2.PhaseInputFieldSpec{
			Name:        f.Name,
			Label:       f.Label,
			Type:        f.Type,
			Required:    f.Required,
			Description: f.Description,
			Placeholder: f.Placeholder,
			Default:     f.Default,
		}
		for _, o := range f.Options {
			field.Options = append(field.Options, v2.PhaseInputOptionSpec{Label: o.Label, Value: o.Value})
		}
		spec.Fields = append(spec.Fields, field)
	}
	return spec
}

func (h *IMMessageHandler) recordWorkflowReviewFeedbackExperience(userID string, intent v2.ReviewIntent, feedback string) {
	if h == nil {
		return
	}
	value, ok := h.workflowReviewExperienceContext.Load(userID)
	if !ok {
		return
	}
	ctx, ok := value.(workflowReviewExperienceContext)
	if !ok || strings.TrimSpace(ctx.TraceID) == "" {
		return
	}
	if workflowReviewIntentEndsCurrentContext(intent) {
		h.workflowReviewExperienceContext.Delete(userID)
	}
	h.recordExperienceLifecycleEvent(ctx.Apply(lifecycle.Event{
		EventType: lifecycle.EventUserFeedbackReceived,
		Outcome:   string(intent),
		Reason:    ctx.PhaseID,
		Query:     feedback,
		CreatedAt: time.Now(),
	}))
}

func workflowReviewIntentEndsCurrentContext(intent v2.ReviewIntent) bool {
	switch intent {
	case v2.ReviewIntentConfirm, v2.ReviewIntentSkip, v2.ReviewIntentCancel, v2.ReviewIntentSwitchTask:
		return true
	default:
		return false
	}
}

func (h *IMMessageHandler) handleWorkflowEngineResponse(engine *v2.WorkflowEngine, userID string, resp *v2.WorkflowResponse, platform string) *IMAgentResponse {
	if resp == nil {
		return nil
	}
	if resp.ShowForm && resp.FormSchema != nil {
		return h.workflowFormResponse(engine, userID, platform, resp)
	}
	if !resp.RunAgentLoop {
		if resp.Complete {
			if adapter, ok := engine.GetCallbacks().(*GUIWorkflowAdapter); ok {
				adapter.ResetSuggestMaximize(userID)
			}
		}
		return &IMAgentResponse{Text: resp.Text}
	}
	if activated, errResp := h.activateWorkflowTaskOrchestrator(engine, userID, resp); errResp != nil {
		return errResp
	} else if !activated {
		if repairResp, repaired := h.repairInvalidCodingTaskBreakdownExecution(engine, userID, resp); repaired {
			return repairResp
		}
	}
	if resp.PhasePrompt != "" {
		h.stashedPhasePrompt.Store(userID, resp.PhasePrompt)
	}
	h.workflowAgentLoopMarker.Store(userID, true)
	if ws := engine.GetActiveWorkflow(userID); ws != nil {
		if orig := extractOriginalRequest(ws, ""); orig != "" {
			h.workflowOriginalRequest.Store(userID, orig)
		}
	}
	if resp.Text != "" {
		if cb := engine.GetCallbacks(); cb != nil {
			_ = cb.SendTextToUser(userID, resp.Text)
		}
	}
	return nil
}

func (h *IMMessageHandler) reviewBarrierResponse(engine *v2.WorkflowEngine, userID string) *IMAgentResponse {
	phaseName := h.workflowReviewPhaseName(engine, userID)
	if phaseName == "" {
		return nil
	}
	lang := h.getWorkflowLang()
	return &IMAgentResponse{Text: i18n.Tf(i18n.MsgWorkflowAwaitingReview, lang, phaseName)}
}

func (h *IMMessageHandler) workflowReviewExecutionBlockedResponse(engine *v2.WorkflowEngine, userID string) *IMAgentResponse {
	phaseName := h.workflowReviewPhaseName(engine, userID)
	if phaseName == "" {
		return nil
	}
	return &IMAgentResponse{Text: i18n.Tf(i18n.MsgWorkflowReviewExecutionBlock, h.getWorkflowLang(), phaseName)}
}

func (h *IMMessageHandler) workflowReviewPhaseName(engine *v2.WorkflowEngine, userID string) string {
	ws := engine.GetActiveWorkflow(userID)
	if ws == nil {
		return ""
	}
	phaseName := ws.CurrentPhase
	if tmpl := engine.GetRegistry().Match(ws.Type); tmpl != nil && ws.PhaseIndex < len(tmpl.Phases) {
		phaseName = tmpl.Phases[ws.PhaseIndex].Name
	}
	return phaseName
}

// handleActiveUnderstanding processes input for a user with an active
// intent understanding session.
func (h *IMMessageHandler) handleActiveUnderstanding(engine *v2.WorkflowEngine, userID, text string) *IMAgentResponse {
	understanding := engine.GetUnderstanding()
	if understanding == nil {
		return nil
	}
	understanding.SetUserLanguage(userID, h.getWorkflowLang())

	reply, ready, cancelled, intent, err := understanding.HandleInput(userID, text)
	if err != nil {
		log.Printf("[WorkflowInterception] understanding HandleInput error for user %s: %v", userID, err)
		if errors.Is(err, v2.ErrIntentUnderstandingContractBreach) {
			return nil
		}
		return &IMAgentResponse{Text: i18n.T(i18n.MsgWorkflowUnderstandError, h.getWorkflowLang())}
	}
	if cancelled {
		lang := h.getWorkflowLang()
		return &IMAgentResponse{Text: i18n.T(i18n.MsgWorkflowCancelled, lang)}
	}
	if ready && intent != nil {
		// Guard: if the LLM returned category="none" or empty with ready=true,
		// it means the task is NOT a workflow task (e.g., content processing).
		// Do NOT call StartWorkflow; fall through to the normal agent loop.
		// The understanding session has already been cleaned up by HandleInput
		// when isReady=true, so no additional cleanup is needed.
		if intent.Category == v2.WorkflowNone || intent.Category == "" {
			log.Printf("[WorkflowInterception] understanding returned ready=true with category=%q for user %s, falling through to agent loop", intent.Category, userID)
			return nil
		}

		// Intent understanding is complete - start the workflow.
		if resp := h.confirmWorkflowStart(userID, text, *intent, reply); resp != nil {
			return resp
		}
		projectPath := h.workflowStartProjectPathForIntent(userID, text, *intent)
		projectPath, prepErr := h.resolveWorkflowProjectPath(projectPath)
		if prepErr != nil {
			log.Printf("[WorkflowInterception] invalid workflow project path for user %s: %v", userID, prepErr)
			return &IMAgentResponse{Error: i18n.Tf(i18n.MsgWorkflowPrepareProjectError, h.getWorkflowLang(), prepErr)}
		}
		state, err := engine.StartWorkflowWithOptions(userID, *intent, v2.WorkflowStartOptions{ProjectPath: projectPath})
		if err != nil {
			log.Printf("[WorkflowInterception] StartWorkflow error for user %s: %v", userID, err)
			return &IMAgentResponse{Error: i18n.Tf(i18n.MsgWorkflowStartError, h.getWorkflowLang(), err)}
		}
		return h.handlePostStartWorkflow(engine, userID, text, state, reply, "")
	}
	return &IMAgentResponse{Text: reply}
}

// handleNeedsUnderstanding starts a new intent understanding session for a
// message that needs LLM classification. The LLM will decide:
//   - Is this a workflow task? (if not, returns nil for the normal agent loop)
//   - Which workflow template?
//   - Structured intent extraction
func (h *IMMessageHandler) handleNeedsUnderstanding(engine *v2.WorkflowEngine, userID, text, platform string) *IMAgentResponse {
	understanding := engine.GetUnderstanding()
	if understanding == nil {
		// No understanding manager; fall through to normal agent loop.
		return nil
	}
	understanding.SetUserLanguage(userID, h.getWorkflowLang())
	var uicForUnderstanding *intent.UnifiedIntentClassifier
	var uicResultForUnderstanding *intent.ClassificationResult

	// Unified classification: UIC fusion produces both IntentLabel and WorkflowType.
	//
	// DESIGN PRINCIPLE: UIC has "fast reject" power but NOT "fast accept" power.
	//
	// UIC is a single-round LLM call with limited context (no conversation
	// history, no knowledge of maclaw's own features). Its classification can
	// be wrong, for example when a GUI automation request superficially looks like a development task.
	//
	// IUM (IntentUnderstandingManager) has richer context (system prompt with
	// maclaw feature descriptions, workflow template descriptions) and can make
	// more accurate judgments. It previously correctly rejected this same intent
	// three times.
	//
	// Therefore:
	//   - UIC can REJECT (fast path): confident non-workflow intent -> skip IUM
	//   - UIC can HINT (pass-through): WorkflowType as hint to IUM for faster processing
	//   - UIC CANNOT ACCEPT (no fast path): never directly start a workflow
	//
	// The "accept" power belongs to IUM (deep semantic confirmation) or the
	// user (via confirmation panel after IUM confirms).
	if uic := h.getUnifiedClassifier(); uic != nil {
		uicForUnderstanding = uic
		uicResult := uic.Classify(intent.MessageContext{
			Text:   text,
			UserID: userID,
		})
		uicResultForUnderstanding = &uicResult

		// UIC says no workflow - check if it's a confident non-workflow signal.
		//
		// Rejection policy based on MayTriggerWorkflow:
		//   - MayTriggerWorkflow=false intents (document_delivery, search, non_coding, etc.):
		//     A semantic result with confidence >= threshold is sufficient.
		//     These intents can NEVER trigger a workflow by definition.
		//   - MayTriggerWorkflow=true intents (coding, office, workflow_task) or Ambiguous/Unknown:
		//     IsWorkflowCandidate returns true -> canReject is false -> falls through to IUM.
		//     This prevents L1 misclassification from blocking a legitimate workflow task.
		if uicResult.WorkflowType == "" {
			isNonWorkflowIntent := !uic.IsWorkflowCandidate(uicResult.Primary)
			threshold := uic.GetWorkflowRejectThreshold()

			if isNonWorkflowIntent && uicResult.Confidence >= threshold {
				log.Printf("[WorkflowInterception] UIC rejected workflow for user %s: "+
					"intent=%s conf=%.2f layer=%d threshold=%.2f text_len=%d",
					userID, uicResult.Primary, uicResult.Confidence, uicResult.Layer, threshold,
					len([]rune(text)))
				return nil
			}
		}

		// Log UIC's recommendation (hint) for diagnostics. The hint is NOT
		// used to directly start a workflow -> it falls through to IUM below.
		if isConcreteWorkflowType(uicResult.WorkflowType) {
			log.Printf("[WorkflowInterception] UIC recommends workflow_type=%s for user %s "+
				"(intent=%s conf=%.2f layer=%d) -> delegating to IUM for confirmation. text_len=%d",
				uicResult.WorkflowType, userID, uicResult.Primary, uicResult.Confidence,
				uicResult.Layer, len([]rune(text)))
		} else {
			// UIC not confident enough or ambiguous.
			log.Printf("[WorkflowInterception] UIC fusion: intent=%s conf=%.2f layer=%d wf=%s - "+
				"not decisive, proceeding to IUM",
				uicResult.Primary, uicResult.Confidence, uicResult.Layer, uicResult.WorkflowType)
		}
	}

	result, err := understanding.Start(userID, text)
	if err != nil {
		log.Printf("[WorkflowInterception] understanding Start error for user %s: %v", userID, err)
		if shouldSurfaceWorkflowUnderstandingStartError(uicForUnderstanding, uicResultForUnderstanding) {
			return &IMAgentResponse{Error: i18n.Tf(i18n.MsgWorkflowUnderstandStartError, h.getWorkflowLang(), err)}
		}
		return nil
	}

	// LLM determined this is NOT a workflow task - trust the LLM's judgment
	// and fall through to the normal agent loop. No session was created.
	if result.Rejected {
		log.Printf("[WorkflowInterception] understanding rejected task for user %s: %q - trusting LLM, no keyword override", userID, truncateRunes(text, 80))
		return nil
	}

	// First-round ready: IUM is confident enough to start the workflow
	// immediately without multi-round clarification. Proceed to confirmation
	// panel (same UX as the old UIC fast-accept path, but with IUM's deeper
	// semantic validation as the gatekeeper instead of UIC's single-round guess).
	if result.Ready && result.Intent != nil {
		// Guard: category="none" or empty with ready=true means not a workflow.
		if result.Intent.Category == v2.WorkflowNone || result.Intent.Category == "" {
			log.Printf("[WorkflowInterception] understanding returned ready=true with category=%q for user %s, falling through to agent loop",
				result.Intent.Category, userID)
			return nil
		}

		log.Printf("[WorkflowInterception] IUM first-round ready for user %s: category=%s conf=%.2f text_len=%d",
			userID, result.Intent.Category, result.Intent.Confidence, len([]rune(text)))

		if resp := h.confirmWorkflowStart(userID, text, *result.Intent, result.Reply); resp != nil {
			return resp
		}
		projectPath := h.workflowStartProjectPathForIntent(userID, text, *result.Intent)
		projectPath, prepErr := h.resolveWorkflowProjectPath(projectPath)
		if prepErr != nil {
			log.Printf("[WorkflowInterception] invalid workflow project path for user %s: %v", userID, prepErr)
			return &IMAgentResponse{Error: i18n.Tf(i18n.MsgWorkflowPrepareProjectError, h.getWorkflowLang(), prepErr)}
		}
		state, err := engine.StartWorkflowWithOptions(userID, *result.Intent, v2.WorkflowStartOptions{ProjectPath: projectPath})
		if err != nil {
			log.Printf("[WorkflowInterception] IUM-driven StartWorkflow error for user %s: %v", userID, err)
			return &IMAgentResponse{Error: i18n.Tf(i18n.MsgWorkflowStartError, h.getWorkflowLang(), err)}
		}
		return h.handlePostStartWorkflow(engine, userID, text, state, result.Reply, platform)
	}

	// LLM says it IS a workflow task but needs clarification - an understanding
	// session has been created. The user will go through multi-round clarification
	// before the workflow actually starts.
	return &IMAgentResponse{Text: result.Reply}
}

func shouldSurfaceWorkflowUnderstandingStartError(uic *intent.UnifiedIntentClassifier, result *intent.ClassificationResult) bool {
	if uic == nil || result == nil {
		return false
	}
	if isConcreteWorkflowType(result.WorkflowType) {
		return result.Confidence >= 0.50
	}
	if result.Primary == intent.LabelUnknown || result.Primary == intent.LabelAmbiguous || result.Primary == intent.LabelContinuation {
		return false
	}
	if !uic.IsWorkflowCandidate(result.Primary) {
		return false
	}
	threshold := uic.GetWorkflowRejectThreshold()
	if threshold <= 0 {
		threshold = intent.DefaultWorkflowRejectThreshold
	}
	return result.Confidence >= threshold
}

// getUnifiedClassifier returns the UIC instance if available, or nil.
// Checks the direct field first (set at construction or by TUI), then
// falls back to h.app for GUI late-init compatibility.
func (h *IMMessageHandler) getUnifiedClassifier() *intent.UnifiedIntentClassifier {
	if h == nil {
		return nil
	}
	if h.unifiedClassifier != nil {
		return h.unifiedClassifier
	}
	if h.app == nil {
		return nil
	}
	return h.app.unifiedClassifier
}

// cancelWorkflowForUser cancels any active workflow and understanding session
// for the given user. Called from /new, /reset, /clear, and /cancel handlers.
