// extractOriginalRequest returns the best available representation of the
// user's original task request from the workflow state. Returns "" if the
// current text already IS the original request (no substitution needed).
//
// Priority:
//  1. Goals[0]: structured callers store the raw user task here
//  2. Summary: only used when no explicit goal is available
//  3. "": text is already the original request
func extractOriginalRequest(state *v2.EngineState, currentText string) string {
	if state == nil {
		return ""
	}
	if len(state.Intent.Goals) > 0 && state.Intent.Goals[0] != "" {
		candidate := state.Intent.Goals[0]
		if candidate != currentText {
			return candidate
		}
		return ""
	}
	if state.Intent.Summary != "" && state.Intent.Summary != currentText {
		return state.Intent.Summary
	}
	return ""
}

func (h *IMMessageHandler) workflowStartProjectPath() string {
	return h.workflowStartProjectPathForOwner("")
}

func (h *IMMessageHandler) workflowStartProjectPathForOwner(ownerID string) string {
	if projectPath := projectPathFromSessionOwnerID(ownerID); projectPath != "" {
		return projectPath
	}
	if h != nil && h.app != nil {
		if projectPath := strings.TrimSpace(h.app.GetCurrentProjectPath()); projectPath != "" {
			return projectPath
		}
	}
	if projectPath := h.traceProjectPath(); projectPath != "" {
		return projectPath
	}
	return strings.TrimSpace(corelib.EffectiveWorkspaceDir())
}

func (h *IMMessageHandler) workflowStartProjectPathForIntent(ownerID, text string, intent v2.StructuredIntent) string {
	if intent.Category == v2.WorkflowCoding {
		candidates := []string{text, intent.Summary}
		candidates = append(candidates, intent.Goals...)
		candidates = append(candidates, intent.Constraints...)
		for _, candidate := range candidates {
			if projectPath := extractCodingDelegateProjectPath(candidate); projectPath != "" {
				return projectPath
			}
		}
	}
	return h.workflowStartProjectPathForOwner(ownerID)
}

