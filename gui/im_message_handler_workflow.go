func workflowAttachmentBypass(engine *v2.WorkflowEngine, userID string, attachments []MessageAttachment, trimmed string) bool {
	if engine != nil {
		if ws := engine.GetActiveWorkflow(userID); ws != nil {
			if tmpl := engine.GetRegistry().Match(ws.Type); ws.IsWaitingForInput(tmpl) {
				return false
			}
		}
	}
	hasImageAttachment := false
	for _, att := range attachments {
		attKind := normalizeIMMediaKind(att.Type)
		if attKind == imMediaImage || attKind == imMediaFile {
			hasImageAttachment = true
			break
		}
	}
	return hasImageAttachment && len([]rune(trimmed)) < 50
}

func workflowHasPendingPhaseForm(engine *v2.WorkflowEngine, userID string) bool {
	if engine == nil {
		return false
	}
	ws := engine.GetActiveWorkflow(userID)
	if ws == nil {
		return false
	}
	tmpl := engine.GetRegistry().Match(ws.Type)
	if tmpl == nil || ws.PhaseIndex < 0 || ws.PhaseIndex >= len(tmpl.Phases) {
		return false
	}
	phase := tmpl.Phases[ws.PhaseIndex]
	if phase.ID != ws.CurrentPhase || phase.InputSchema == nil {
		return false
	}
	return !ws.PhaseFormSubmitted && !ws.PhaseFormSkipped && len(ws.PhaseFormData) == 0
}

func isWorkflowFormDirectRunCommand(text string) bool {
	trimmed := strings.ToLower(strings.TrimSpace(text))
	trimmed = strings.Trim(trimmed, " .\u3002!\uff01")
	switch trimmed {
	case "\u76f4\u63a5\u5199", "\u76f4\u63a5\u6267\u884c", "\u76f4\u63a5\u505a", "\u76f4\u63a5\u5f00\u59cb", "\u76f4\u63a5\u751f\u6210", "\u5f00\u5de5", "\u5f00\u59cb", "\u542f\u52a8", "\u7ee7\u7eed", "\u8df3\u8fc7", "\u8df3\u8fc7\u8868\u5355", "\u4e0d\u7528\u586b", "\u4e0d\u586b\u4e86", "go", "go ahead", "start", "continue", "skip", "skip form":
		return true
	}
	return strings.Contains(trimmed, "\u4e0d\u7528\u586b") || strings.Contains(trimmed, "\u8df3\u8fc7\u8868\u5355") || strings.Contains(trimmed, "\u76f4\u63a5") && (strings.Contains(trimmed, "\u505a") || strings.Contains(trimmed, "\u5199") || strings.Contains(trimmed, "\u6267\u884c") || strings.Contains(trimmed, "\u751f\u6210"))
}

func isWorkflowCancelText(text string) bool {
	trimmed := strings.ToLower(strings.TrimSpace(text))
	trimmed = strings.Trim(trimmed, " .\u3002!\uff01")
	switch trimmed {
	case "/cancel", "cancel", "abort", "stop", "quit", "\u53d6\u6d88", "\u505c\u6b62", "\u653e\u5f03", "\u9000\u51fa":
		return true
	}
	return false
}

func buildPendingWorkflowConfirmation(userID, text string, intent v2.StructuredIntent, startReply string, lang string, projectPaths ...string) *pendingConfirmation {
	now := time.Now()
	goals := normalizeWorkflowConfirmationGoals(intent.Goals)
	originalText := workflowConfirmationTaskText(text, goals, intent.Summary)
	projectPath := ""
	if len(projectPaths) > 0 {
		projectPath = strings.TrimSpace(projectPaths[0])
	}
	targetPaths := make([]string, 0, 1)
	if projectPath != "" {
		targetPaths = append(targetPaths, projectPath)
	}
	summary := i18n.Tf(i18n.MsgWorkflowConfirmSummary, lang, intent.Category, originalText)
	if len(goals) == 0 {
		if intentSummary := strings.TrimSpace(intent.Summary); intentSummary != "" {
			summary += "\n\n" + intentSummary
		}
	}
	return &pendingConfirmation{
		ID:                  fmt.Sprintf("confirm-%d", now.UnixNano()),
		UserID:              strings.TrimSpace(userID),
		OriginalText:        originalText,
		ResumeText:          originalText,
		Summary:             summary,
		TaskType:            "workflow:" + string(intent.Category),
		TargetPaths:         targetPaths,
		PlannedActions:      []string{i18n.T(i18n.MsgWorkflowConfirmAction1, lang), i18n.T(i18n.MsgWorkflowConfirmAction2, lang), i18n.T(i18n.MsgWorkflowConfirmAction3, lang)},
		RiskFlags:           []string{i18n.T(i18n.MsgWorkflowConfirmRisk1, lang)},
		RevisionHints:       []string{i18n.T(i18n.MsgWorkflowConfirmRevision1, lang), i18n.T(i18n.MsgWorkflowConfirmRevision2, lang)},
		Status:              confirmationStatusPending,
		CreatedAt:           now,
		UpdatedAt:           now,
		LastProjectPath:     projectPath,
		WorkflowType:        string(intent.Category),
		WorkflowSummary:     strings.TrimSpace(intent.Summary),
		WorkflowGoals:       goals,
		WorkflowConstraints: append([]string(nil), intent.Constraints...),
		WorkflowConfidence:  intent.Confidence,
		WorkflowStartReply:  strings.TrimSpace(startReply),
	}
}

func normalizeWorkflowConfirmationGoals(goals []string) []string {
	normalized := make([]string, 0, len(goals))
	for _, goal := range goals {
		if trimmed := strings.TrimSpace(goal); trimmed != "" {
			normalized = append(normalized, trimmed)
		}
	}
	return normalized
}

func workflowConfirmationTaskText(text string, goals []string, summary string) string {
	if len(goals) > 0 {
		return goals[0]
	}
	if summary := strings.TrimSpace(summary); summary != "" {
		return summary
	}
	return strings.TrimSpace(text)
}

func firstNonEmptyWorkflowString(values ...string) string {
	for _, value := range values {
		if trimmed := strings.TrimSpace(value); trimmed != "" {
			return trimmed
		}
	}
	return ""
}

