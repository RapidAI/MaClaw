var objRe = /\{\s*zh\s*:\s*('(?:\\'|[^'])*'|"(?:\\"|[^"])*")\s*,\s*en\s*:\s*('(?:\\'|[^'])*'|"(?:\\"|[^"])*")\s*\}/g;
var pairRe = /\[('(?:\\'|[^'])*'|"(?:\\"|[^"])*")\s*,\s*('(?:\\'|[^'])*'|"(?:\\"|[^"])*")\]/g;

function scan(src, kind) {
  var missing = [];
  var re = kind === 'pair' ? pairRe : objRe;
  var m;
  var rx = new RegExp(re.source, 'g');
  while ((m = rx.exec(src))) {
    var a = eval(m[1]);
    var b = eval(m[2]);
    var zh = kind === 'pair' ? a : a;
    var en = kind === 'pair' ? b : b;
    if (kind === 'pair' && a === 'English' && b === '中文') continue;
    if (!translate(en, zh)) missing.push(JSON.stringify(en) + ' || ' + JSON.stringify(zh));
  }
  return missing;
}

