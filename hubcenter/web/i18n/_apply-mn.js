function patchObjects(src) {
  return src.replace(objRe, function(full, zhLit, enLit) {
    var zh = eval(zhLit);
    var en = eval(enLit);
    var mn = translate(en, zh);
    return full.replace(/\s*\}$/, ', mn: ' + JSON.stringify(mn) + '}');
  });
}

function patchPairs(src) {
  return src.replace(pairRe, function(full, aLit, bLit) {
    var zh = eval(aLit);
    var en = eval(bLit);
    if (zh === 'English' && en === '中文') return full;
    var mn = translate(en, zh);
    return '[' + aLit + ', ' + bLit + ', ' + JSON.stringify(mn) + ']';
  });
}

