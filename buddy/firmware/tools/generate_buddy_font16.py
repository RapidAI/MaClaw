#!/usr/bin/env python3
"""Generate the buddy 16px bitmap font used for small UI text.

Why a second table: the UI composes a 360x360 canvas and buddy_display point
samples it 3:2 onto the 240x240 NV3023. A glyph is pixel-exact on that glass
only when every source pixel maps to exactly one glass pixel, i.e. when the
source cell is drawn at 1.5x (24 canvas px -> 16 glass px) or 3x. The 24px CJK
table therefore has exactly one crisp size, 24 glass px; anything smaller was
being resampled and lost rows and columns.

This table supplies the small sizes: GNU Unifont glyphs (8x16 for Latin, 16x16
for ideographs) drawn at 1.5x land on 16 glass px with no resampling.

Layout of the generated cjk16.bin, in this order:
  ASCII 0x20..0x7E                       95 glyphs
  the explicit extras below              17 glyphs
  0x3000..0x303F (CJK punctuation)       64 glyphs
  0x4E00..0x9FFF (CJK unified)        20992 glyphs
  0xFF00..0xFFEF (full-width forms)     240 glyphs
Each glyph is 32 bytes: 16 rows, 2 bytes per row, MSB leftmost. Narrow (8px
wide) glyphs sit in the high byte so a single reader handles both widths.
After the glyph data comes a 1-bit-per-glyph width map (MSB first), 1 = wide.

Input: a unifont .hex file (https://unifoundry.com/pub/unifont/). Unifont is
dual licensed GPLv2+ with the font embedding exception, and OFL 1.1.

Outputs (next to main/):
  cjk16.bin               packed glyphs + width map
  buddy_font16_index.h    range table and extras list
"""

from __future__ import annotations

from pathlib import Path
import sys

HERE = Path(__file__).resolve().parent
MAIN = HERE.parent / "main"

GLYPH_ROWS = 16
GLYPH_BYTES = GLYPH_ROWS * 2

# Ranges are contiguous, so a four-entry table beats a 21k codepoint array.
RANGES = [
    (0x0020, 0x007E),
    (0x3000, 0x303F),
    (0x4E00, 0x9FFF),
    (0xFF00, 0xFFEF),
]
# Anything the UI prints outside those ranges: degree, middle dot, multiply,
# dashes, ellipsis, Celsius, arrows, bullets, stars, check and cross.
EXTRAS = [
    0x00B0, 0x00B7, 0x00D7,
    0x2013, 0x2014, 0x2026, 0x2103,
    0x2190, 0x2191, 0x2192, 0x2193,
    0x25CB, 0x25CF, 0x2605, 0x2606,
    0x2713, 0x2717,
]


def load_hex(path: Path) -> dict[int, bytes]:
    glyphs: dict[int, bytes] = {}
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        line = line.strip()
        if not line or ":" not in line:
            continue
        code, data = line.split(":", 1)
        cp = int(code, 16)
        if cp > 0xFFFF:
            continue
        raw = bytes.fromhex(data)
        # Unifont stores 16 rows; width is 8 or 16 columns for the BMP.
        if len(raw) == 32:
            glyphs[cp] = raw
        elif len(raw) == 16:
            # 8px wide: keep it in the high byte of each 16-bit row.
            wide = bytearray()
            for row in range(GLYPH_ROWS):
                wide += bytes((raw[row], 0))
            glyphs[cp] = bytes(wide)
    return glyphs


def codepoints() -> list[tuple[int, bool]]:
    """(codepoint, is_wide) in the order the blob stores them."""
    out: list[tuple[int, bool]] = []
    for lo, hi in RANGES:
        out.extend((cp, cp >= 0x2E80) for cp in range(lo, hi + 1))
    return out


def main() -> int:
    hex_path = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / "unifont.hex"
    if not hex_path.is_file():
        print(f"missing unifont hex: {hex_path}", file=sys.stderr)
        return 2
    src = load_hex(hex_path)

    total = (RANGES[0][1] - RANGES[0][0] + 1) + len(EXTRAS)
    for lo, hi in RANGES[1:]:
        total += hi - lo + 1

    blob = bytearray()
    widths = bytearray((total + 7) // 8)
    bit = 0
    missing: list[int] = []

    def emit(cp: int, wide_default: bool) -> None:
        nonlocal bit
        raw = src.get(cp)
        if raw is None:
            missing.append(cp)
            raw = bytes(GLYPH_BYTES)
        blob.extend(raw)
        # A cell is 16px wide on the glass unless every row keeps its low byte
        # clear, i.e. the glyph really is 8px wide.
        wide = wide_default and not _is_narrow(raw)
        if wide:
            widths[bit >> 3] |= 1 << (7 - (bit & 7))
        bit += 1

    for cp in range(0x0020, 0x007F):
        emit(cp, False)
    extra_base = len(blob) // GLYPH_BYTES
    for cp in EXTRAS:
        emit(cp, cp in (0x2605, 0x2606))
    range_rows = []
    for lo, hi in RANGES[1:]:
        range_rows.append((lo, hi, len(blob) // GLYPH_BYTES))
        for cp in range(lo, hi + 1):
            emit(cp, True)

    if missing:
        print(f"warning: {len(missing)} codepoints absent from unifont "
              f"(first: U+{missing[0]:04X})", file=sys.stderr)

    blob.extend(widths)

    out_bin = MAIN / "cjk16.bin"
    out_bin.write_bytes(blob)

    lines = [
        "/* Generated by tools/generate_buddy_font16.py. Do not edit. */",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"#define BUDDY16_GLYPH_COUNT {total}",
        f"#define BUDDY16_ASCII_FIRST 0x0020",
        f"#define BUDDY16_ASCII_LAST 0x007E",
        f"#define BUDDY16_EXTRA_BASE {extra_base}",
        "",
        "/* {first, last, base glyph index} for the contiguous blocks. */",
        "static const uint32_t s_buddy16_ranges[][3] = {",
    ]
    for lo, hi, base in range_rows:
        lines.append(f"    {{0x{lo:04X}, 0x{hi:04X}, {base}}},")
    lines += [
        "};",
        f"#define BUDDY16_RANGE_COUNT {len(range_rows)}",
        "",
        "static const uint16_t s_buddy16_extras[] = {",
    ]
    for i in range(0, len(EXTRAS), 6):
        chunk = ", ".join(f"0x{cp:04X}" for cp in EXTRAS[i:i + 6])
        lines.append(f"    {chunk},")
    lines += [
        "};",
        f"#define BUDDY16_EXTRA_COUNT {len(EXTRAS)}",
        "",
    ]
    (MAIN / "buddy_font16_index.h").write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out_bin} ({len(blob)} bytes, {total} glyphs)")
    return 0


def _is_narrow(raw: bytes) -> bool:
    """True when every row keeps its low byte clear, i.e. an 8px glyph."""
    return all(raw[row * 2 + 1] == 0 for row in range(GLYPH_ROWS))


if __name__ == "__main__":
    raise SystemExit(main())
