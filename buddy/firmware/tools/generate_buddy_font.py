#!/usr/bin/env python3
"""Generate the buddy auxiliary 24x24 CJK glyph table.

The firmware reuses iot-agentos' cjk24_cjk.bin for U+4E00-U+9FFF. That table
has no punctuation, no full-width forms and no symbols, so task titles such as
"整理会议纪要，并导出 Word（终稿）" would render boxes. This script renders a
small extension table with the same geometry (24 rows x 3 bytes, MSB-first) as
the existing packed font.

Outputs (next to main/):
  cjk24_ext.bin        one 72-byte glyph per entry, in the index order
  buddy_font_ext_index.h  sorted codepoint array for binary search
"""

from __future__ import annotations

from pathlib import Path
import struct

from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
MAIN = HERE.parent / "main"
FONT_PATH = Path(r"C:\Windows\Fonts\msyh.ttc")
SIZE = 24
GLYPH_BYTES = SIZE * 3

# Ranges: CJK punctuation and full-width forms. Explicit extras cover units,
# arrows, bullets and check marks the UI may print.
RANGES = [(0x3000, 0x3040), (0xFF00, 0xFFF0)]
EXTRAS = [
    0x00B0,  # °
    0x00B7,  # ·
    0x00D7,  # ×
    0x2013, 0x2014,  # – —
    0x2026,  # …
    0x2103,  # ℃
    0x2190, 0x2191, 0x2192, 0x2193,  # arrows
    0x25CF, 0x25CB,  # ● ○
    0x2605, 0x2606,  # ★ ☆
    0x2713, 0x2717,  # ✓ ✗
]


def codepoints() -> list[int]:
    cps: set[int] = set(EXTRAS)
    for lo, hi in RANGES:
        cps.update(range(lo, hi))
    return sorted(cps)


def glyph_rows(font: ImageFont.FreeTypeFont, char: str) -> list[int]:
    image = Image.new("1", (SIZE, SIZE), 0)
    draw = ImageDraw.Draw(image)
    try:
        draw.text((0, 0), char, fill=1, font=font, anchor="lt")
    except Exception:
        return [0] * SIZE
    rows = []
    for y in range(SIZE):
        row = 0
        for x in range(SIZE):
            if image.getpixel((x, y)):
                row |= 1 << (SIZE - 1 - x)
        rows.append(row)
    return rows


def main() -> None:
    font = ImageFont.truetype(str(FONT_PATH), SIZE)
    cps = codepoints()
    blob = bytearray()
    for cp in cps:
        rows = glyph_rows(font, chr(cp))
        for row in rows:
            blob += struct.pack(">I", row)[1:]  # 24 bits per row, MSB-first
    out_bin = MAIN / "cjk24_ext.bin"
    out_bin.write_bytes(blob)

    lines = [
        "/* Generated by tools/generate_buddy_font.py. Do not edit. */",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "static const uint32_t s_buddy_ext_codepoints[] = {",
    ]
    for i in range(0, len(cps), 8):
        chunk = ", ".join(f"0x{cp:04X}" for cp in cps[i : i + 8])
        lines.append(f"    {chunk},")
    lines += [
        "};",
        f"#define BUDDY_EXT_GLYPH_COUNT {len(cps)}",
        "",
    ]
    (MAIN / "buddy_font_ext_index.h").write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out_bin} ({len(blob)} bytes, {len(cps)} glyphs)")


if __name__ == "__main__":
    main()
