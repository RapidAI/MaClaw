// Command genspec renders buddy/protocol/spec.json into the firmware header
// so the device and the host share one source of truth for limits and cadence.
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"sort"
)

type spec struct {
	Proto            int `json:"proto"`
	MaxLineBytes     int `json:"max_line_bytes"`
	MaxCurrent       int `json:"max_current_tasks"`
	MaxTitleBytes    int `json:"max_title_bytes"`
	HeartbeatMS      int `json:"heartbeat_ms"`
	OfflineMS        int `json:"offline_ms"`
	StaleMS          int `json:"stale_ms"`
	WeatherRefreshMS int `json:"weather_refresh_ms"`
	WeatherStaleMS   int `json:"weather_stale_ms"`
	Display          struct {
		Width  int  `json:"width"`
		Height int  `json:"height"`
		Round  bool `json:"round"`
	} `json:"display"`
	Types struct {
		HostToDevice []string `json:"host_to_device"`
		DeviceToHost []string `json:"device_to_host"`
	} `json:"types"`
}

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: genspec <spec.json> <out.h>")
		os.Exit(2)
	}
	raw, err := os.ReadFile(os.Args[1])
	if err != nil {
		fmt.Fprintf(os.Stderr, "read spec: %v\n", err)
		os.Exit(1)
	}
	var s spec
	if err := json.Unmarshal(raw, &s); err != nil {
		fmt.Fprintf(os.Stderr, "parse spec: %v\n", err)
		os.Exit(1)
	}
	names := append(append([]string{}, s.Types.HostToDevice...), s.Types.DeviceToHost...)
	uniq := map[string]bool{}
	names = names[:0]
	for _, n := range append(append([]string{}, s.Types.HostToDevice...), s.Types.DeviceToHost...) {
		if !uniq[n] {
			uniq[n] = true
			names = append(names, n)
		}
	}
	sort.Strings(names)

	out := "/* Generated by buddy/protocol/cmd/genspec from protocol/spec.json. Do not edit. */\n"
	out += "#pragma once\n\n"
	out += fmt.Sprintf("#define BUDDY_PROTO_VERSION %d\n", s.Proto)
	out += fmt.Sprintf("#define BUDDY_MAX_LINE_BYTES %d\n", s.MaxLineBytes)
	out += fmt.Sprintf("#define BUDDY_MAX_CURRENT_TASKS %d\n", s.MaxCurrent)
	out += fmt.Sprintf("#define BUDDY_MAX_TITLE_BYTES %d\n", s.MaxTitleBytes)
	out += fmt.Sprintf("#define BUDDY_HEARTBEAT_MS %d\n", s.HeartbeatMS)
	out += fmt.Sprintf("#define BUDDY_OFFLINE_MS %d\n", s.OfflineMS)
	out += fmt.Sprintf("#define BUDDY_STALE_MS %d\n", s.StaleMS)
	out += fmt.Sprintf("#define BUDDY_WEATHER_REFRESH_MS %d\n", s.WeatherRefreshMS)
	out += fmt.Sprintf("#define BUDDY_WEATHER_STALE_MS %d\n", s.WeatherStaleMS)
	out += fmt.Sprintf("#define BUDDY_DISPLAY_WIDTH %d\n", s.Display.Width)
	out += fmt.Sprintf("#define BUDDY_DISPLAY_HEIGHT %d\n", s.Display.Height)
	out += fmt.Sprintf("#define BUDDY_DISPLAY_ROUND %d\n\n", boolInt(s.Display.Round))
	out += "/* Message type strings accepted on the wire. */\n"
	for _, n := range names {
		out += fmt.Sprintf("#define BUDDY_MSG_%s \"%s\"\n", upperSnake(n), n)
	}
	if err := os.WriteFile(os.Args[2], []byte(out), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "write header: %v\n", err)
		os.Exit(1)
	}
}

func boolInt(b bool) int {
	if b {
		return 1
	}
	return 0
}

func upperSnake(s string) string {
	out := make([]rune, 0, len(s))
	for _, r := range s {
		if r >= 'a' && r <= 'z' {
			r -= 'a' - 'A'
		}
		out = append(out, r)
	}
	return string(out)
}
