#!/usr/bin/env python3
"""Generate the five buddy notification sounds.

Each clip is 16 kHz, 16-bit, stereo interleaved (L=R) PCM, which is exactly
what the ES8311/I2S path plays. The clips are embedded in the firmware image
and selected per event (running / complete / standby) by the host config.

Outputs:
  firmware/main/sounds.pcm          concatenated clips
  firmware/main/buddy_sound_index.h offsets/lengths for the C player
  build/verify/sounds/soundN.wav    audition copies (not embedded)
"""

from __future__ import annotations

from pathlib import Path
import wave

import numpy as np

SR = 16000
HERE = Path(__file__).resolve().parent
MAIN = HERE.parent / "firmware" / "main"
PREVIEW = HERE.parents[1] / "build" / "verify" / "sounds"


def envelope(n: int, decay: float, attack_s: float = 0.005) -> np.ndarray:
    t = np.arange(n) / SR
    env = np.exp(-decay * t)
    attack = max(1, int(attack_s * SR))
    env[:attack] *= np.linspace(0.0, 1.0, attack)
    return env


def tone(freq: float, dur: float, decay: float, harmonics: list[tuple[float, float]],
         attack_s: float = 0.005) -> np.ndarray:
    n = int(SR * dur)
    t = np.arange(n) / SR
    signal = np.zeros(n, dtype=np.float64)
    for mult, amp in harmonics:
        signal += amp * np.sin(2 * np.pi * freq * mult * t)
    return signal * envelope(n, decay, attack_s)


def sweep(f0: float, f1: float, dur: float, decay: float) -> np.ndarray:
    n = int(SR * dur)
    t = np.arange(n) / SR
    freq = f0 + (f1 - f0) * (t / dur)
    phase = 2 * np.pi * np.cumsum(freq) / SR
    return np.sin(phase) * envelope(n, decay, 0.01)


def chord(freqs: list[float], dur: float, decay: float) -> np.ndarray:
    n = int(SR * dur)
    out = np.zeros(n, dtype=np.float64)
    for f in freqs:
        out += tone(f, dur, decay, [(1.0, 0.6), (2.0, 0.12)], attack_s=0.06)
    return out / max(1.0, len(freqs))


def silence(ms: int) -> np.ndarray:
    return np.zeros(int(SR * ms / 1000), dtype=np.float64)


def normalize(signal: np.ndarray, peak: float = 0.55) -> np.ndarray:
    top = float(np.max(np.abs(signal))) if signal.size else 0.0
    if top > 0:
        signal = signal * (peak / top)
    return signal


def build_clips() -> list[np.ndarray]:
    c6, e6 = 1046.50, 1318.51
    a5 = 880.0
    c5, e5, g5, g4 = 523.25, 659.26, 783.99, 392.0
    clips = [
        # 1. light two-note chime (default)
        np.concatenate([tone(c6, 0.18, 9.0, [(1, 1.0), (2, 0.3)], 0.003),
                        tone(e6, 0.30, 7.0, [(1, 1.0), (2, 0.3)], 0.003)]),
        # 2. bright bell
        tone(a5, 0.85, 4.5, [(1, 1.0), (2.76, 0.45), (5.4, 0.2)], 0.002),
        # 3. warm chord
        chord([c5, e5, g5], 0.80, 3.5),
        # 4. rising glide
        sweep(c5, g5, 0.60, 3.0),
        # 5. low two-note
        np.concatenate([tone(g4, 0.28, 6.0, [(1, 1.0), (2, 0.2)], 0.004),
                        tone(c5, 0.42, 5.0, [(1, 1.0), (2, 0.2)], 0.004)]),
    ]
    return [normalize(c) for c in clips]


def main() -> None:
    clips = build_clips()
    PREVIEW.mkdir(parents=True, exist_ok=True)
    blob = bytearray()
    offsets, lengths = [], []
    for i, clip in enumerate(clips, start=1):
        # 5 ms fade-out avoids a click when the PA is muted.
        fade = int(0.005 * SR)
        if clip.size > fade:
            clip[-fade:] *= np.linspace(1.0, 0.0, fade)
        pcm = np.round(clip * 32767.0).astype("<i2")
        stereo = np.column_stack([pcm, pcm]).astype("<i2").tobytes()
        offsets.append(len(blob))
        lengths.append(len(stereo))
        blob += stereo

        with wave.open(str(PREVIEW / f"sound{i}.wav"), "wb") as wf:
            wf.setnchannels(2)
            wf.setsampwidth(2)
            wf.setframerate(SR)
            wf.writeframes(stereo)

    (MAIN / "sounds.pcm").write_bytes(blob)
    lines = [
        "/* Generated by tools/generate_sounds.py. Do not edit. */",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "static const uint32_t s_sound_offsets[] = {",
        "    " + ", ".join(f"{o}u" for o in offsets) + ",",
        "};",
        "static const uint32_t s_sound_lengths[] = {",
        "    " + ", ".join(f"{l}u" for l in lengths) + ",",
        "};",
        f"#define BUDDY_SOUND_COUNT {len(clips)}",
        "",
    ]
    (MAIN / "buddy_sound_index.h").write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {MAIN / 'sounds.pcm'} ({len(blob)} bytes, {len(clips)} clips)")
    print(f"wrote previews to {PREVIEW}")


if __name__ == "__main__":
    main()
