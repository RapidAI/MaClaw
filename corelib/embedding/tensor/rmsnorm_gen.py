#!/usr/bin/env python3
# Generates rmsnorm_arm64.s (n multiple of 16).
L=[];e=L.append
W=lambda x,c='': e(f'\tWORD ${x:#08x} // {c}')
fmla=lambda d,n,m:0x4E20CC00|(m<<16)|(n<<5)|d
fmul=lambda d,n,m:0x6E20DC00|(m<<16)|(n<<5)|d
fadd=lambda d,n,m:0x4E20D400|(m<<16)|(n<<5)|d
faddp=lambda d,n,m:0x6E20D400|(m<<16)|(n<<5)|d
e('//go:build arm64\n\n// Code generated by rmsnorm_gen.py; DO NOT EDIT.\n\n#include "textflag.h"\n')
e('// func sumSq16NEON(x *float32, n int) float32')
e('TEXT ·sumSq16NEON(SB), NOSPLIT, $0-20\n\tMOVD x+0(FP), R0\n\tMOVD n+8(FP), R1')
for i in range(4): e(f'\tVEOR V{i}.B16, V{i}.B16, V{i}.B16')
e('ssl:\n\tVLD1.P 64(R0), [V4.S4, V5.S4, V6.S4, V7.S4]')
for i in range(4): W(fmla(i,4+i,4+i))
e('\tSUB $16, R1, R1\n\tCBNZ R1, ssl')
W(fadd(0,0,1));W(fadd(2,2,3));W(fadd(0,0,2));W(faddp(0,0,0));W(0x7E30D800,'FADDP S0')
e('\tFMOVS F0, ret+16(FP)\n\tRET\n')
e('// func scaleMul16NEON(out, x, w *float32, n int, scale float32)')
e('TEXT ·scaleMul16NEON(SB), NOSPLIT, $0-36\n\tMOVD out+0(FP), R0\n\tMOVD x+8(FP), R1\n\tMOVD w+16(FP), R2\n\tMOVD n+24(FP), R3\n\tFMOVS scale+32(FP), F16\n\tVDUP V16.S[0], V16.S4')
e('sml:\n\tVLD1.P 64(R1), [V0.S4, V1.S4, V2.S4, V3.S4]\n\tVLD1.P 64(R2), [V4.S4, V5.S4, V6.S4, V7.S4]')
for i in range(4): W(fmul(i,i,16)); W(fmul(i,i,4+i))
e('\tVST1.P [V0.S4, V1.S4, V2.S4, V3.S4], 64(R0)\n\tSUB $16, R3, R3\n\tCBNZ R3, sml\n\tRET')
open('rmsnorm_arm64.s','w').write('\n'.join(L)+'\n')
