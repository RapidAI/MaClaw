// Row-scale VNNI M3 kernels for EmbeddingGemma short sequences (seq==3).
// Same contract as the M8 kernels, including the 16-lane ColBias subtract
// before the horizontal sum. Three activation rows:
//   out[r][n] = aS[r] · Σ_blk bS[n][blk]·Σ_i (aQ[r][i]−128)·int8(packed[n][i])
// aQ: 3 rows × K bytes u8(+128), stride K. aS: 3 f32, stride 4.
// ns must be even; loop covers col pairs [ns, ne) stepping 2.

// func gemmaVNNIRowM3N24PackedAVX512(out *float32, aQ *byte, aS *float32, packed *byte, bS *float32, N, ns, ne int, bias *float32)
// K=768 (24 blocks, 12 ticks of 64B per column pair).
TEXT ·gemmaVNNIRowM3N24PackedAVX512(SB), NOSPLIT, $80-72
	MOVQ out+0(FP), AX
	MOVQ AX, 0(SP)
	MOVQ aQ+8(FP), AX
	MOVQ AX, 8(SP)
	MOVQ aS+16(FP), AX
	MOVQ AX, 16(SP)
	MOVQ packed+24(FP), AX
	MOVQ AX, 24(SP)
	MOVQ bS+32(FP), AX
	MOVQ AX, 32(SP)
	MOVQ N+40(FP), AX
	MOVQ AX, 40(SP)
	MOVQ ne+56(FP), AX
	MOVQ AX, 48(SP)
	MOVQ ns+48(FP), AX
	MOVQ AX, 56(SP)
	MOVQ bias+64(FP), CX
	MOVQ CX, 64(SP)

	MOVQ 24(SP), DI
	MOVQ AX, R12
	IMULQ $768, R12
	ADDQ R12, DI
	LEAQ 768(DI), R15
	MOVQ 32(SP), R13
	MOVQ AX, R12
	IMULQ $96, R12
	ADDQ R12, R13
	LEAQ 96(R13), R14
	MOVQ 8(SP), SI
	MOVQ 16(SP), R8

r3v24n:
	MOVQ 56(SP), R12
	MOVQ 48(SP), CX
	ADDQ $1, R12
	CMPQ R12, CX
	JGE  r3v24done

	VXORPS Z0, Z0, Z0
	VXORPS Z1, Z1, Z1
	VXORPS Z2, Z2, Z2
	VXORPS Z3, Z3, Z3
	VXORPS Z4, Z4, Z4
	VXORPS Z5, Z5, Z5
	VXORPS Z27, Z27, Z27
	VXORPS Z31, Z31, Z31
	MOVQ $12, CX

r3v24k:
	PREFETCHT0 192(DI)
	PREFETCHT0 192(R15)
	VMOVDQU64 (DI), Z16
	VMOVDQU64 (R15), Z17
	// Z24 = [bS[n][b]×8 | bS[n][b+1]×8]
	VMOVSS (R13), X28
	VBROADCASTSS X28, Y24
	VMOVSS 4(R13), X28
	VBROADCASTSS X28, Y25
	VINSERTF32X8 $1, Y25, Z24, Z24
	// Z23 = [bS[n+1][b]×8 | bS[n+1][b+1]×8]
	VMOVSS (R14), X28
	VBROADCASTSS X28, Y23
	VMOVSS 4(R14), X28
	VBROADCASTSS X28, Y25
	VINSERTF32X8 $1, Y25, Z23, Z23

	// row 0
	VMOVDQU64 (SI), Z18
	VPXORD Z22, Z22, Z22
	VPDPBUSD Z16, Z18, Z22
	VCVTDQ2PS Z22, Z22
	VFMADD231PS Z24, Z22, Z0
	VPXORD Z22, Z22, Z22
	VPDPBUSD Z17, Z18, Z22
	VCVTDQ2PS Z22, Z22
	VFMADD231PS Z23, Z22, Z3
	// row 1
	VMOVDQU64 768(SI), Z18
	VPXORD Z22, Z22, Z22
	VPDPBUSD Z16, Z18, Z22
	VCVTDQ2PS Z22, Z22
	VFMADD231PS Z24, Z22, Z1
	VPXORD Z22, Z22, Z22
	VPDPBUSD Z17, Z18, Z22
	VCVTDQ2PS Z22, Z22
	VFMADD231PS Z23, Z22, Z4
	// row 2
	VMOVDQU64 1536(SI), Z18
	VPXORD Z22, Z22, Z22
	VPDPBUSD Z16, Z18, Z22
	VCVTDQ2PS Z22, Z22
	VFMADD231PS Z24, Z22, Z2
	VPXORD Z22, Z22, Z22
	VPDPBUSD Z17, Z18, Z22
	VCVTDQ2PS Z22, Z22
	VFMADD231PS Z23, Z22, Z5

	ADDQ $64, DI
	ADDQ $64, R15
	ADDQ $64, SI
	ADDQ $8, R13
	ADDQ $8, R14
	DECQ CX
	JNZ  r3v24k

	MOVQ 0(SP), BX
	MOVQ 56(SP), AX
	MOVQ 40(SP), DX
	MOVQ 64(SP), CX
	MOVQ AX, R12
	SHLQ $6, R12
	ADDQ R12, CX
	VMOVDQU64 (CX), Z27
	VMOVDQU64 64(CX), Z31
	MOVQ AX, R12
	SHLQ $2, R12
	ADDQ BX, R12

	VSUBPS Z27, Z0, Z0
	VEXTRACTF32X8 $1, Z0, Y28
	VADDPS Y0, Y28, Y28
	VEXTRACTF32X4 $1, Y28, X29
	VADDPS X29, X28, X28
	VSHUFPD $1, X28, X28, X29
	VADDPS X28, X29, X28
	VMOVSHDUP X28, X29
	VADDSS X28, X29, X28
	VMULSS (R8), X28, X28
	VMOVSS X28, (R12)
	VSUBPS Z31, Z3, Z3
	VEXTRACTF32X8 $1, Z3, Y28
	VADDPS Y3, Y28, Y28
	VEXTRACTF32X4 $1, Y28, X29
	VADDPS X29, X28, X28
	VSHUFPD $1, X28, X28, X29
	VADDPS X28, X29, X28
	VMOVSHDUP X28, X29
	VADDSS X28, X29, X28
	VMULSS (R8), X28, X28
	VMOVSS X28, 4(R12)
	LEAQ (R12)(DX*4), R12

	VSUBPS Z27, Z1, Z1
	VEXTRACTF32X8 $1, Z1, Y28
	VADDPS Y1, Y28, Y28
	VEXTRACTF32X4 $1, Y28, X29
	VADDPS X29, X28, X28
	VSHUFPD $1, X28, X28, X29
	VADDPS X28, X29, X28
	VMOVSHDUP X28, X29
	VADDSS X28, X29, X28
	VMULSS 4(R8), X28, X28
	VMOVSS X28, (R12)
	VSUBPS Z31, Z4, Z4
	VEXTRACTF32X8 $1, Z4, Y28
	VADDPS Y4, Y28, Y28
	VEXTRACTF32X4 $1, Y28, X29
	VADDPS X29, X28, X28
	VSHUFPD $1, X28, X28, X29
	VADDPS X28, X29, X28
	VMOVSHDUP X28, X29
	VADDSS X28, X29, X28
	VMULSS 4(R8), X28, X28
	VMOVSS X28, 4(R12)
	LEAQ (R12)(DX*4), R12

	VSUBPS Z27, Z2, Z2
	VEXTRACTF32X8 $1, Z2, Y28
	VADDPS Y2, Y28, Y28
	VEXTRACTF32X4 $1, Y28, X29
	VADDPS X29, X28, X28
	VSHUFPD $1, X28, X28, X29
	VADDPS X28, X29, X28
	VMOVSHDUP X28, X29
	VADDSS X28, X29, X28
	VMULSS 8(R8), X28, X28
	VMOVSS X28, (R12)
	VSUBPS Z31, Z5, Z5
	VEXTRACTF32X8 $1, Z5, Y28
	VADDPS Y5, Y28, Y28
	VEXTRACTF32X4 $1, Y28, X29
	VADDPS X29, X28, X28
	VSHUFPD $1, X28, X28, X29
	VADDPS X28, X29, X28
	VMOVSHDUP X28, X29
	VADDSS X28, X29, X28
	VMULSS 8(R8), X28, X28
	VMOVSS X28, 4(R12)

	ADDQ $2, 56(SP)
	ADDQ $768, DI
	ADDQ $768, R15
	ADDQ $96, R13
	ADDQ $96, R14
	SUBQ $768, SI
	JMP  r3v24n

r3v24done:
	RET

