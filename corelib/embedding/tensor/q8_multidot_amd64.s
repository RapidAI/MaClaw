	VADDPS X0, X4, X0
	VHADDPS X0, X0, X0
	VHADDPS X0, X0, X0
	MOVSS X0, (R11)
	VEXTRACTF128 $1, Y1, X4
	VADDPS X1, X4, X1
	VHADDPS X1, X1, X1
	VHADDPS X1, X1, X1
	MOVSS X1, 4(R11)
