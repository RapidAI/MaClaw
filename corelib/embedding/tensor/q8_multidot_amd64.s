	VADDPS X3, X4, X3
	VHADDPS X3, X3, X3
	VHADDPS X3, X3, X3
	MOVSS X3, 12(R11)
	VZEROUPPER
	RET

// func q8DualMultiDot4ScaledAVX2(out *[8]float32, a *float32, K int, data *byte, scales0, scales1 *float32, rowOff0, rowOff1, nBlocks int)
// Frame: out+0, a+8, K+16, data+24, scales0+32, scales1+40, rowOff0+48, rowOff1+56, nBlocks+64 = 72
TEXT ·q8DualMultiDot4ScaledAVX2(SB), NOSPLIT, $0-72
	MOVQ out+0(FP), R11
	MOVQ a+8(FP), SI
	MOVQ K+16(FP), AX
	MOVQ data+24(FP), DI
	MOVQ scales0+32(FP), R13
	MOVQ scales1+40(FP), R14
	MOVQ nBlocks+64(FP), CX

	ADDQ rowOff0+48(FP), DI
	MOVQ data+24(FP), R15
	ADDQ rowOff1+56(FP), R15

	SHLQ $2, AX
	// Keep A base SI; recompute row bases each group from SI+offset via R8 walk
	// Acc Y0-Y3 B0, Y4-Y7 B1
	VXORPS Y0, Y0, Y0
	VXORPS Y1, Y1, Y1
	VXORPS Y2, Y2, Y2
	VXORPS Y3, Y3, Y3
	VXORPS Y4, Y4, Y4
	VXORPS Y5, Y5, Y5
	VXORPS Y6, Y6, Y6
	VXORPS Y7, Y7, Y7

	// Row pointers
	MOVQ SI, R8
	LEAQ (SI)(AX*1), R9
	LEAQ (R9)(AX*1), R10
	LEAQ (R10)(AX*1), R12

	TESTQ CX, CX
	JZ   dmd4s_hsum

