// func q8MultiDot8AVX2(out *[8]float32, a *float32, K int, data *byte, rowOff, nBlocks int)
// 8 A rows; uses Y0-Y7 accumulators, Y14 scale, Y15 dequant B.
TEXT ·q8MultiDot8AVX2(SB), NOSPLIT, $0-48
	MOVQ out+0(FP), R11
	MOVQ a+8(FP), SI
	MOVQ K+16(FP), AX
	MOVQ data+24(FP), DI
	MOVQ rowOff+32(FP), R8
	MOVQ nBlocks+40(FP), CX
	ADDQ R8, DI

	SHLQ $2, AX               // AX = K*4 row stride

	// Zero Y0-Y7
	VXORPS Y0, Y0, Y0
	VXORPS Y1, Y1, Y1
	VXORPS Y2, Y2, Y2
	VXORPS Y3, Y3, Y3
	VXORPS Y4, Y4, Y4
	VXORPS Y5, Y5, Y5
	VXORPS Y6, Y6, Y6
	VXORPS Y7, Y7, Y7

	// k float offset in R8 (bytes within each row)
	XORQ R8, R8

	TESTQ CX, CX
	JZ   hsum8

block8:
	// scale
	MOVWLZX (DI), AX
	MOVL  AX, DX
	SHRL  $15, DX
	SHLL  $31, DX
	MOVL  AX, R9
	SHRL  $10, R9
	ANDL  $0x1f, R9
	MOVL  AX, R10
	ANDL  $0x3ff, R10
	TESTL R9, R9
	JZ    s0_8
	CMPL  R9, $31
	JE    si_8
	ADDL  $112, R9
	SHLL  $23, R9
	SHLL  $13, R10
	ORL   R9, DX
	ORL   R10, DX
	JMP   sok_8
s0_8:
	JMP   sok_8
si_8:
	ORL   $0x7f800000, DX
	SHLL  $13, R10
	ORL   R10, DX
sok_8:
	MOVL  DX, X14
	VBROADCASTSS X14, Y14

	// Reload K stride (AX was clobbered by scale bits)
	MOVQ K+16(FP), AX
	SHLQ $2, AX

	// Process 4 groups of 8; for each group update all 8 rows
	// Group index g=0..3, A offset = R8 + g*32

	// --- g=0 ---
	VPMOVSXBD 2(DI), X12
	VPMOVSXBD 6(DI), X13
	VINSERTI128 $1, X13, Y12, Y12
	VCVTDQ2PS Y12, Y12
	VMULPS Y14, Y12, Y15      // Y15 = B dequant chunk

	// row r at SI + r*AX + R8
	MOVQ SI, R9
	ADDQ R8, R9
	// r0
	VMOVUPS (R9), Y13
	VFMADD231PS Y13, Y15, Y0
	// r1
	ADDQ AX, R9
	VMOVUPS (R9), Y13
	VFMADD231PS Y13, Y15, Y1
	// r2
	ADDQ AX, R9
	VMOVUPS (R9), Y13
	VFMADD231PS Y13, Y15, Y2
	// r3
	ADDQ AX, R9
	VMOVUPS (R9), Y13
	VFMADD231PS Y13, Y15, Y3
	// r4
	ADDQ AX, R9
	VMOVUPS (R9), Y13
	VFMADD231PS Y13, Y15, Y4
	// r5
	ADDQ AX, R9
	VMOVUPS (R9), Y13
	VFMADD231PS Y13, Y15, Y5
	// r6
	ADDQ AX, R9
	VMOVUPS (R9), Y13
	VFMADD231PS Y13, Y15, Y6
	// r7
	ADDQ AX, R9
	VMOVUPS (R9), Y13
	VFMADD231PS Y13, Y15, Y7

	// --- g=1 offset +32 ---
	VPMOVSXBD 10(DI), X12
	VPMOVSXBD 14(DI), X13
	VINSERTI128 $1, X13, Y12, Y12
	VCVTDQ2PS Y12, Y12
	VMULPS Y14, Y12, Y15

	MOVQ SI, R9
	ADDQ R8, R9
	ADDQ $32, R9
	VMOVUPS (R9), Y13
	VFMADD231PS Y13, Y15, Y0
	ADDQ AX, R9
	VMOVUPS (R9), Y13
	VFMADD231PS Y13, Y15, Y1
	ADDQ AX, R9
	VMOVUPS (R9), Y13
	VFMADD231PS Y13, Y15, Y2
	ADDQ AX, R9
	VMOVUPS (R9), Y13
	VFMADD231PS Y13, Y15, Y3
	ADDQ AX, R9
	VMOVUPS (R9), Y13
	VFMADD231PS Y13, Y15, Y4
	ADDQ AX, R9
	VMOVUPS (R9), Y13
	VFMADD231PS Y13, Y15, Y5
	ADDQ AX, R9
	VMOVUPS (R9), Y13
	VFMADD231PS Y13, Y15, Y6
	ADDQ AX, R9
	VMOVUPS (R9), Y13
	VFMADD231PS Y13, Y15, Y7

	// --- g=2 offset +64 ---
	VPMOVSXBD 18(DI), X12
	VPMOVSXBD 22(DI), X13
	VINSERTI128 $1, X13, Y12, Y12
	VCVTDQ2PS Y12, Y12
	VMULPS Y14, Y12, Y15

	MOVQ SI, R9
	ADDQ R8, R9
	ADDQ $64, R9
	VMOVUPS (R9), Y13
	VFMADD231PS Y13, Y15, Y0
	ADDQ AX, R9
