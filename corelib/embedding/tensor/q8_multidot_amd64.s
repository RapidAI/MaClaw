// Shared f16->f32 conversion for Q8 scale (bits in AX -> f32 bits in DX).
// Clobbers: DX, R9, R10. Input: AX = f16 zero-extended.

// func q8MultiDot4AVX2(out *[4]float32, a *float32, K int, data *byte, rowOff, nBlocks int)
//
// out[i] = sum dequant(B_row) * A[i]
// a is contiguous [4][K], K = nBlocks*32.
//
// Frame:
//   out     +0
//   a       +8
//   K       +16
//   data    +24
//   rowOff  +32
//   nBlocks +40
TEXT ·q8MultiDot4AVX2(SB), NOSPLIT, $0-48
	MOVQ out+0(FP), R11
	MOVQ a+8(FP), SI
	MOVQ K+16(FP), AX
	MOVQ data+24(FP), DI
	MOVQ rowOff+32(FP), R8
	MOVQ nBlocks+40(FP), CX
	ADDQ R8, DI               // DI = start of Q8 row

	// Row stride bytes = K*4
	SHLQ $2, AX               // AX = K*4
	// Row pointers: R8,R9,R10,DX  (DX repurposed after scale)
	MOVQ SI, R8
	LEAQ (SI)(AX*1), R9
	LEAQ (R9)(AX*1), R10
	LEAQ (R10)(AX*1), R12     // row3 in R12 (save DX for scale)

	// Accumulators Y0-Y3
	VXORPS Y0, Y0, Y0
	VXORPS Y1, Y1, Y1
	VXORPS Y2, Y2, Y2
	VXORPS Y3, Y3, Y3

	TESTQ CX, CX
	JZ   hsum4

block4:
	// --- f16 scale -> Y15 broadcast ---
	MOVWLZX (DI), AX
	MOVL  AX, DX
	SHRL  $15, DX
	SHLL  $31, DX
	MOVL  AX, R13
	SHRL  $10, R13
	ANDL  $0x1f, R13
	MOVL  AX, R14
	ANDL  $0x3ff, R14
	TESTL R13, R13
	JZ    scale0_4
	CMPL  R13, $31
	JE    scalei_4
	ADDL  $112, R13
	SHLL  $23, R13
	SHLL  $13, R14
	ORL   R13, DX
	ORL   R14, DX
	JMP   scale_ok_4
scale0_4:
	JMP   scale_ok_4
scalei_4:
	ORL   $0x7f800000, DX
	SHLL  $13, R14
	ORL   R14, DX
scale_ok_4:
	MOVL  DX, X15
	VBROADCASTSS X15, Y15     // Y15 = scale

	// Group 0: bytes 2..9 -> 8 floats
	VPMOVSXBD 2(DI), X4
	VPMOVSXBD 6(DI), X5
	VINSERTI128 $1, X5, Y4, Y4
	VCVTDQ2PS Y4, Y4
	VMULPS Y15, Y4, Y4        // Y4 = dequant B[0:8]

	VMOVUPS (R8), Y5
	VFMADD231PS Y5, Y4, Y0
	VMOVUPS (R9), Y5
	VFMADD231PS Y5, Y4, Y1
	VMOVUPS (R10), Y5
	VFMADD231PS Y5, Y4, Y2
	VMOVUPS (R12), Y5
	VFMADD231PS Y5, Y4, Y3

	// Group 1: bytes 10..17 -> B[8:16]
	VPMOVSXBD 10(DI), X4
	VPMOVSXBD 14(DI), X5
	VINSERTI128 $1, X5, Y4, Y4
	VCVTDQ2PS Y4, Y4
	VMULPS Y15, Y4, Y4

	VMOVUPS 32(R8), Y5
	VFMADD231PS Y5, Y4, Y0
	VMOVUPS 32(R9), Y5
	VFMADD231PS Y5, Y4, Y1
	VMOVUPS 32(R10), Y5
	VFMADD231PS Y5, Y4, Y2
	VMOVUPS 32(R12), Y5
	VFMADD231PS Y5, Y4, Y3

	// Group 2: bytes 18..25 -> B[16:24]
	VPMOVSXBD 18(DI), X4
	VPMOVSXBD 22(DI), X5
	VINSERTI128 $1, X5, Y4, Y4
	VCVTDQ2PS Y4, Y4
	VMULPS Y15, Y4, Y4

	VMOVUPS 64(R8), Y5
	VFMADD231PS Y5, Y4, Y0
	VMOVUPS 64(R9), Y5
	VFMADD231PS Y5, Y4, Y1
	VMOVUPS 64(R10), Y5
	VFMADD231PS Y5, Y4, Y2
	VMOVUPS 64(R12), Y5
	VFMADD231PS Y5, Y4, Y3

	// Group 3: bytes 26..33 -> B[24:32]
	VPMOVSXBD 26(DI), X4
	VPMOVSXBD 30(DI), X5
	VINSERTI128 $1, X5, Y4, Y4
	VCVTDQ2PS Y4, Y4
	VMULPS Y15, Y4, Y4

	VMOVUPS 96(R8), Y5
	VFMADD231PS Y5, Y4, Y0
	VMOVUPS 96(R9), Y5
	VFMADD231PS Y5, Y4, Y1
	VMOVUPS 96(R10), Y5
	VFMADD231PS Y5, Y4, Y2
	VMOVUPS 96(R12), Y5
	VFMADD231PS Y5, Y4, Y3

	// Advance: +34 Q8 block, +128 bytes (32 floats) per A row
	ADDQ $34, DI
	ADDQ $128, R8
	ADDQ $128, R9
	ADDQ $128, R10
	ADDQ $128, R12
	DECQ CX
	JNZ  block4

hsum4:
	VEXTRACTF128 $1, Y0, X4
	VADDPS X0, X4, X0
	VSHUFPD $1, X0, X0, X15
	VADDPS X0, X15, X0
	VMOVSHDUP X0, X15
	VADDSS X0, X15, X0
	MOVSS X0, (R11)

	VEXTRACTF128 $1, Y1, X4
	VADDPS X1, X4, X1
	VSHUFPD $1, X1, X1, X15
	VADDPS X1, X15, X1
	VMOVSHDUP X1, X15
	VADDSS X1, X15, X1
	MOVSS X1, 4(R11)

	VEXTRACTF128 $1, Y2, X4
	VADDPS X2, X4, X2
	VSHUFPD $1, X2, X2, X15
	VADDPS X2, X15, X2
	VMOVSHDUP X2, X15
	VADDSS X2, X15, X2
	MOVSS X2, 8(R11)

	VEXTRACTF128 $1, Y3, X4
	VADDPS X3, X4, X3
	VSHUFPD $1, X3, X3, X15
	VADDPS X3, X15, X3
	VMOVSHDUP X3, X15
	VADDSS X3, X15, X3
	MOVSS X3, 12(R11)

	VZEROUPPER
	RET

