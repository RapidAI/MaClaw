	VXORPS Y2, Y2, Y2
	VXORPS Y3, Y3, Y3
	TESTQ CX, CX
	JZ   md4s_hsum

	// Dual-block when even
	MOVQ CX, R14
	SHRQ $1, R14
	TESTQ R14, R14
	JZ   md4s_odd

