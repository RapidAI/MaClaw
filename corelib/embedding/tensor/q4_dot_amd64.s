// func q4Q8Dual8AccumVNNIASM(out *float32, aQ *int8, aS *float32,
// q40, q41 *byte, s0, s1 *float32, m, n, N int, b0, b1 float32)
// Fixed K=2048 (64 Q4/Q8 blocks), eight activation rows and two adjacent
// Q4 rows. Each VNNI result is reduced and dequantized before the next block;
// bias, residual and stores form the fused epilogue.
TEXT ·q4Q8Dual8AccumVNNIASM(SB), NOSPLIT, $0-88
	MOVQ out+0(FP), R11
	MOVQ aQ+8(FP), R12
	MOVQ aS+16(FP), R13
	MOVQ q40+24(FP), R14
	MOVQ q41+32(FP), R15
	MOVQ $0x0f0f0f0f0f0f0f0f, SI
	VMOVQ SI, X0
	VPBROADCASTB X0, X0
	MOVQ $0x0808080808080808, SI
	VMOVQ SI, X1
	VPBROADCASTB X1, X1
	XORQ R10, R10

q4q8_dual8_row:
	// Activation row r starts at q[r*32], with a 256-byte block stride.
	MOVQ R12, BX
	MOVQ R10, AX
	SHLQ $5, AX
	ADDQ AX, BX
	MOVQ R13, SI
	MOVQ R10, AX
	SHLQ $2, AX
	ADDQ AX, SI
	MOVQ R14, DI
	MOVQ R15, R8
	MOVQ s0+40(FP), R9
	MOVQ s1+48(FP), DX
	VXORPS X12, X12, X12
	VXORPS X13, X13, X13
	MOVQ $64, CX

q4q8_dual8_block:
	VZEROUPPER
	VMOVDQU (BX), Y4
	// q4 row 0 -> scalar float accumulation X12.
	VMOVDQU (DI), X2
	VPAND X0, X2, X3
	VPSRLW $4, X2, X2
	VPAND X0, X2, X2
	VPSUBB X1, X3, X3
	VPSUBB X1, X2, X2
	VINSERTI128 $0, X3, Y3, Y3
	VINSERTI128 $1, X2, Y3, Y3
	VPXORD Y5, Y5, Y5
	VPDPBUSD Y3, Y4, Y5
	VEXTRACTI128 $1, Y5, X6
	VPADDD X6, X5, X5
	VPHADDD X5, X5, X5
	VPHADDD X5, X5, X5
	VMOVD X5, AX
	CVTSL2SS AX, X5
	MOVSS (SI), X6
	MULSS (R9), X6
	MULSS X6, X5
	ADDSS X5, X12
	// q4 row 1 -> scalar float accumulation X13, reusing loaded activation.
	VMOVDQU (R8), X2
	VPAND X0, X2, X3
	VPSRLW $4, X2, X2
	VPAND X0, X2, X2
	VPSUBB X1, X3, X3
	VPSUBB X1, X2, X2
	VINSERTI128 $0, X3, Y3, Y3
	VINSERTI128 $1, X2, Y3, Y3
	VPXORD Y5, Y5, Y5
	VPDPBUSD Y3, Y4, Y5
	VEXTRACTI128 $1, Y5, X6
	VPADDD X6, X5, X5
	VPHADDD X5, X5, X5
	VPHADDD X5, X5, X5
	VMOVD X5, AX
	CVTSL2SS AX, X5
	MOVSS (SI), X6
	MULSS (DX), X6
	MULSS X6, X5
	ADDSS X5, X13
	ADDQ $256, BX
	ADDQ $8, SI
	ADDQ $16, DI
	ADDQ $16, R8
	ADDQ $4, R9
	ADDQ $4, DX
	DECQ CX
	JNZ q4q8_dual8_block

	MOVSS b0+80(FP), X5
	ADDSS X5, X12
	MOVSS b1+84(FP), X5
	ADDSS X5, X13
	// offset = ((m+r)*N+n)*4
	MOVQ m+56(FP), AX
	ADDQ R10, AX
	IMULQ N+72(FP), AX
	ADDQ n+64(FP), AX
	SHLQ $2, AX
	MOVSS (R11)(AX*1), X5
	ADDSS X12, X5
	MOVSS X5, (R11)(AX*1)
	MOVSS 4(R11)(AX*1), X5
	ADDSS X13, X5
	MOVSS X5, 4(R11)(AX*1)
	INCQ R10
	CMPQ R10, $8
	JL q4q8_dual8_row
	VZEROUPPER
	RET
