// func dotQ4Q8BlockASM(q4, q8 *byte) int32
// q4 has low nibbles for q[0:16] and high nibbles for q[16:32].
TEXT ·dotQ4Q8BlockASM(SB), NOSPLIT, $0-24
	MOVQ q4+0(FP), AX
	MOVQ q8+8(FP), BX
	XORQ CX, CX
	XORQ DX, DX
q4q8_loop:
	MOVBQZX (AX)(CX*1), SI
	MOVQ SI, DI
	ANDQ $15, SI
	SUBQ $8, SI
	MOVBQSX (BX)(CX*1), R8
	IMULQ R8, SI
	ADDQ SI, DX
	SHRQ $4, DI
	ANDQ $15, DI
	SUBQ $8, DI
	MOVBQSX 16(BX)(CX*1), R8
	IMULQ R8, DI
	ADDQ DI, DX
	INCQ CX
	CMPQ CX, $16
	JL q4q8_loop
	MOVL DX, ret+16(FP)
	RET

// func dotQ4Q8BlocksASM(out *int32, q4, q8 *byte, nBlocks int)
TEXT ·dotQ4Q8BlocksASM(SB), NOSPLIT, $0-32
	MOVQ out+0(FP), R11
	MOVQ q4+8(FP), AX
	MOVQ q8+16(FP), BX
	MOVQ nBlocks+24(FP), R10
	XORQ R9, R9
q4q8_blocks_outer:
	XORQ CX, CX
	XORQ DX, DX
q4q8_blocks_inner:
	MOVBQZX (AX)(CX*1), SI
	MOVQ SI, DI
	ANDQ $15, SI
	SUBQ $8, SI
	MOVBQSX 2(BX)(CX*1), R8
	IMULQ R8, SI
	ADDQ SI, DX
	SHRQ $4, DI
	ANDQ $15, DI
	SUBQ $8, DI
	MOVBQSX 18(BX)(CX*1), R8
	IMULQ R8, DI
	ADDQ DI, DX
	INCQ CX
	CMPQ CX, $16
	JL q4q8_blocks_inner
	MOVL DX, (R11)(R9*4)
	ADDQ $16, AX
	ADDQ $34, BX
	INCQ R9
	CMPQ R9, R10
	JL q4q8_blocks_outer
	RET

// func dotQ4Q8BlocksAVX2ASM(out *int32, q4, q8 *byte, nBlocks int)
// Vectorized Q4_0 × Q8_0 block dot. Q4's low/high nibbles map to the
// first/second 16 Q8 values respectively. Output is one int32 sum per block.
TEXT ·dotQ4Q8BlocksAVX2ASM(SB), NOSPLIT, $32-32
	MOVQ out+0(FP), R11
	MOVQ q4+8(FP), AX
	MOVQ q8+16(FP), BX
	MOVQ nBlocks+24(FP), R10
	MOVQ $0x0f0f0f0f0f0f0f0f, SI
	VMOVQ SI, X0
	VPBROADCASTB X0, X0
	MOVQ $0x0808080808080808, SI
	VMOVQ SI, X1
	VPBROADCASTB X1, X1
	VPCMPEQW Y7, Y7, Y7
	XORQ R9, R9
q4q8_avx_outer:
	VMOVDQU (AX), X2
	VPAND X0, X2, X3
	VPSRLW $4, X2, X4
	VPAND X0, X4, X4
	VPSUBB X3, X1, X3
	VPSUBB X4, X1, X4
	VPMOVSXBW X3, Y3
	VPMOVSXBW 2(BX), Y5
	VPMULLW Y5, Y3, Y3
	VPMADDWD Y7, Y3, Y3
	VPMOVSXBW X4, Y4
	VPMOVSXBW 18(BX), Y5
	VPMULLW Y5, Y4, Y4
	VPMADDWD Y7, Y4, Y4
	VPADDD Y4, Y3, Y3
	VMOVDQU Y3, 0(SP)
	MOVL 0(SP), DX
	ADDL 4(SP), DX
	ADDL 8(SP), DX
	ADDL 12(SP), DX
	ADDL 16(SP), DX
	ADDL 20(SP), DX
	ADDL 24(SP), DX
	ADDL 28(SP), DX
	MOVL DX, (R11)(R9*4)
	ADDQ $16, AX
	ADDQ $34, BX
	INCQ R9
	CMPQ R9, R10
	JL q4q8_avx_outer
	VZEROUPPER
	RET

// func q4Q8BlockVNNIASM(out *int32, aQ, q4 *byte)
// Produces eight VPDPBUSD lanes (four products each).
TEXT ·q4Q8BlockVNNIASM(SB), NOSPLIT, $0-32
	MOVQ out+0(FP), AX
	MOVQ aQ+8(FP), BX
	MOVQ q4+16(FP), CX
	MOVQ $0x0f0f0f0f0f0f0f0f, SI
	VMOVQ SI, X0
	VPBROADCASTB X0, X0
	MOVQ $0x0808080808080808, SI
	VMOVQ SI, X1
	VPBROADCASTB X1, X1
	VMOVDQU (CX), X2
	VPAND X0, X2, X3
	VPSRLW $4, X2, X4
	VPAND X0, X4, X4
	VPSUBB X1, X3, X3
	VPSUBB X1, X4, X4
	VZEROUPPER
	VINSERTI128 $0, X3, Y3, Y3
	VINSERTI128 $1, X4, Y3, Y3
	VMOVDQU (BX), Y4
	VPXORD Y5, Y5, Y5
	VPDPBUSD Y3, Y4, Y5
	VMOVDQU Y5, (AX)
	VZEROUPPER
	RET

