// func fmaddIntoAVX2(out, a, b *float32, n int)
// out[i] += a[i]*b[i] for n elements (n multiple of 8, n>=8).
// Frame: out+0, a+8, b+16, n+24
// Unroll x4 (32 floats) for SenseVoice hidden=512 (16 iters).
TEXT ·fmaddIntoAVX2(SB), NOSPLIT, $0-32
	MOVQ out+0(FP), DI
	MOVQ a+8(FP), SI
	MOVQ b+16(FP), DX
	MOVQ n+24(FP), CX

	MOVQ CX, R8
	SHRQ $5, R8               // n/32
	TESTQ R8, R8
	JZ   fmadd16chk

fmadd32:
	VMOVUPS (DI), Y0
	VMOVUPS (SI), Y1
	VMOVUPS (DX), Y2
	VFMADD231PS Y1, Y2, Y0
	VMOVUPS Y0, (DI)
	VMOVUPS 32(DI), Y0
	VMOVUPS 32(SI), Y1
	VMOVUPS 32(DX), Y2
	VFMADD231PS Y1, Y2, Y0
	VMOVUPS Y0, 32(DI)
	VMOVUPS 64(DI), Y0
	VMOVUPS 64(SI), Y1
	VMOVUPS 64(DX), Y2
	VFMADD231PS Y1, Y2, Y0
	VMOVUPS Y0, 64(DI)
	VMOVUPS 96(DI), Y0
	VMOVUPS 96(SI), Y1
	VMOVUPS 96(DX), Y2
	VFMADD231PS Y1, Y2, Y0
	VMOVUPS Y0, 96(DI)

	ADDQ $128, DI
	ADDQ $128, SI
	ADDQ $128, DX
	DECQ R8
	JNZ  fmadd32

fmadd16chk:
	MOVQ n+24(FP), CX
	ANDQ $31, CX              // remainder after 32-wide
	MOVQ CX, R8
	SHRQ $4, R8               // /16
	TESTQ R8, R8
	JZ   fmadd8

fmadd16:
	VMOVUPS (DI), Y0
	VMOVUPS (SI), Y1
	VMOVUPS (DX), Y2
	VFMADD231PS Y1, Y2, Y0
	VMOVUPS Y0, (DI)
	VMOVUPS 32(DI), Y0
	VMOVUPS 32(SI), Y1
	VMOVUPS 32(DX), Y2
	VFMADD231PS Y1, Y2, Y0
	VMOVUPS Y0, 32(DI)
	ADDQ $64, DI
	ADDQ $64, SI
	ADDQ $64, DX
	DECQ R8
	JNZ  fmadd16

fmadd8:
	MOVQ n+24(FP), CX
	ANDQ $15, CX
	SHRQ $3, CX
	TESTQ CX, CX
	JZ   fmadd_done

	VMOVUPS (DI), Y0
	VMOVUPS (SI), Y1
	VMOVUPS (DX), Y2
	VFMADD231PS Y1, Y2, Y0
	VMOVUPS Y0, (DI)

fmadd_done:
	VZEROUPPER
	RET

