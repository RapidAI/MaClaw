// func copy128AVX2(dst, src *float32)
// Copy 128 float32 (512 bytes); 32 floats/iter → 4 iters.
TEXT ·copy128AVX2(SB), NOSPLIT, $0-16
	MOVQ dst+0(FP), DI
	MOVQ src+8(FP), SI
	MOVQ $4, CX
c128_loop:
	VMOVUPS (SI), Y0
	VMOVUPS 32(SI), Y1
	VMOVUPS 64(SI), Y2
	VMOVUPS 96(SI), Y3
	VMOVUPS Y0, (DI)
	VMOVUPS Y1, 32(DI)
	VMOVUPS Y2, 64(DI)
	VMOVUPS Y3, 96(DI)
	ADDQ $128, SI
	ADDQ $128, DI
	DECQ CX
	JNZ  c128_loop
	VZEROUPPER
	RET

// func copy128MulAVX2(dst, src *float32, scale float32)
// dst[i] = src[i] * scale for 128 floats (attention Q pack + 1/sqrt(d)).
// Frame: dst+0 src+8 scale+16
// 32 floats/iter → 4 iters.
TEXT ·copy128MulAVX2(SB), NOSPLIT, $0-20
	MOVQ dst+0(FP), DI
	MOVQ src+8(FP), SI
	MOVSS scale+16(FP), X0
	VBROADCASTSS X0, Y0
	MOVQ $4, CX
c128m_loop:
	VMOVUPS (SI), Y1
	VMULPS Y0, Y1, Y1
	VMOVUPS Y1, (DI)
	VMOVUPS 32(SI), Y1
	VMULPS Y0, Y1, Y1
	VMOVUPS Y1, 32(DI)
	VMOVUPS 64(SI), Y1
	VMULPS Y0, Y1, Y1
	VMOVUPS Y1, 64(DI)
	VMOVUPS 96(SI), Y1
	VMULPS Y0, Y1, Y1
	VMOVUPS Y1, 96(DI)
	ADDQ $128, SI
	ADDQ $128, DI
	DECQ CX
	JNZ  c128m_loop
	VZEROUPPER
	RET

// func packQKV128AVX2(dstQ, dstK, dstV, srcQ, srcK, srcV *float32, scale float32)
// One head pack: Q*=scale, K/V plain copy. Interleaved 16-float chunks for ILP.
// Frame: dQ+0 dK+8 dV+16 sQ+24 sK+32 sV+40 scale+48 → 52
TEXT ·packQKV128AVX2(SB), NOSPLIT, $0-52
	MOVQ dstQ+0(FP), R8
	MOVQ dstK+8(FP), R9
	MOVQ dstV+16(FP), R10
	MOVQ srcQ+24(FP), SI
	MOVQ srcK+32(FP), DI
	MOVQ srcV+40(FP), BX
	MOVSS scale+48(FP), X0
	VBROADCASTSS X0, Y0
	// 8 iters × 16 floats
	MOVQ $8, CX
pqkv_loop:
	// Q * scale
	VMOVUPS (SI), Y1
	VMULPS Y0, Y1, Y1
	VMOVUPS Y1, (R8)
	VMOVUPS 32(SI), Y1
	VMULPS Y0, Y1, Y1
	VMOVUPS Y1, 32(R8)
	// K
	VMOVUPS (DI), Y2
	VMOVUPS 32(DI), Y3
	VMOVUPS Y2, (R9)
	VMOVUPS Y3, 32(R9)
	// V
	VMOVUPS (BX), Y4
	VMOVUPS 32(BX), Y5
	VMOVUPS Y4, (R10)
	VMOVUPS Y5, 32(R10)

	ADDQ $64, SI
	ADDQ $64, DI
	ADDQ $64, BX
	ADDQ $64, R8
	ADDQ $64, R9
	ADDQ $64, R10
	DECQ CX
	JNZ  pqkv_loop
	VZEROUPPER
	RET

