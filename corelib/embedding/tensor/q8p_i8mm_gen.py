#!/usr/bin/env python3
# Generates q8p_i8mm_arm64.s: X2 activation x I8MM-packed weight tile (SMMLA)
# and the NEON X2 activation quantizer. Layouts: see q8p_x2.go.
L=[];e=L.append
W=lambda x,c: e(f'\tWORD ${x:#08x} // {c}')
smmla=lambda d,n,m:0x4E80A400|(m<<16)|(n<<5)|d
shl8=lambda d,n:0x4F285400|(n<<5)|d
zip1d=lambda d,n,m:0x4EC03800|(m<<16)|(n<<5)|d
zip2d=lambda d,n,m:0x4EC07800|(m<<16)|(n<<5)|d
fmul=lambda d,n,m:0x6E20DC00|(m<<16)|(n<<5)|d
fmla=lambda d,n,m:0x4E20CC00|(m<<16)|(n<<5)|d
scvtf=lambda d,n:0x4E21D800|(n<<5)|d
e('//go:build arm64\n\n// Code generated by q8p_i8mm_gen.py; DO NOT EDIT.\n\n#include "textflag.h"\n')
e('// func q8pTileX2I8MM(out *float32, aq1, aq2 *int8, rpStride int, as4 *float32, as4Stride int, qb *byte, sb *float32, nb int)')
e('// One 16-column half of a 4-row x 32-col tile. out: 64 floats [rp][j][r0c0,r0c1,r1c0,r1c1], accumulated.')
e('// V0-V15 int acc (rp*8+j); V16-V23 act; V24-V31 weights / duplicated col scales.')
e('TEXT ·q8pTileX2I8MM(SB), NOSPLIT, $0-72')
e('\tMOVD out+0(FP), R0\n\tMOVD aq1+8(FP), R1\n\tMOVD aq2+16(FP), R9\n\tMOVD rpStride+24(FP), R2\n\tMOVD as4+32(FP), R3\n\tMOVD as4Stride+40(FP), R4\n\tMOVD qb+48(FP), R5\n\tMOVD sb+56(FP), R6\n\tMOVD nb+64(FP), R7')
e('\tADD R2, R1, R8\n\tADD R2, R9, R10\n\tADD R4, R3, R11\n\tADD $128, R0, R14')
for i in range(16): e(f'\tVEOR V{i}.B16, V{i}.B16, V{i}.B16')
e('blk:')
def passk(ra,rb):
    e(f'\tVLD1.P 64({ra}), [V16.B16, V17.B16, V18.B16, V19.B16]')
    e(f'\tVLD1.P 64({rb}), [V20.B16, V21.B16, V22.B16, V23.B16]')
    for c in range(4):
        e('\tVLD1.P 64(R5), [V24.B16, V25.B16, V26.B16, V27.B16]')
        e('\tVLD1.P 64(R5), [V28.B16, V29.B16, V30.B16, V31.B16]')
        for rp in range(2):
            for j in range(8):
                W(smmla(rp*8+j,16+rp*4+c,24+j),f'SMMLA V{rp*8+j}, V{16+rp*4+c}, V{24+j}')
passk('R1','R8')
for i in range(16): W(shl8(i,i),f'SHL V{i}.4S, #8')
e('\tSUB $512, R5, R5')
passk('R9','R10')
e('\tADD $512, R5, R5')
e('\tVLD1 (R6), [V16.S4, V17.S4, V18.S4, V19.S4]')
e('\tADD $128, R6, R6')
for k in range(4):
    W(zip1d(24+2*k,16+k,16+k),f'ZIP1 V{24+2*k}.2D'); W(zip2d(25+2*k,16+k,16+k),f'ZIP2 V{25+2*k}.2D')
e('\tVLD1.P 16(R3), [V16.S4]')
e('\tVLD1.P 16(R11), [V17.S4]')
e('\tMOVD R0, R12\n\tMOVD R14, R13')
for rp,ro in ((0,'R12'),(1,'R13')):
    for gq in range(2):
        e(f'\tVLD1 ({ro}), [V18.S4, V19.S4, V20.S4, V21.S4]')
        for jj in range(4):
            j=gq*4+jj; a=rp*8+j; t=22+(jj&1)
            W(fmul(t,16+rp,24+j),f'FMUL V{t}, V{16+rp}, V{24+j}')
            W(scvtf(a,a),f'SCVTF V{a}')
            W(fmla(18+jj,a,t),f'FMLA V{18+jj}, V{a}, V{t}')
            e(f'\tVEOR V{a}.B16, V{a}.B16, V{a}.B16')
        e(f'\tVST1.P [V18.S4, V19.S4, V20.S4, V21.S4], 64({ro})')
e('\tSUB $1, R7, R7\n\tCBNZ R7, blk\n\tRET\n')

# X2 quantizer: one row, nb blocks. q1/q2 base already offset to (rp, sub); block stride 64 B, chunk stride 16 B.
fabs=lambda d,n:0x4EA0F800|(n<<5)|d
fmax=lambda d,n,m:0x4E20F400|(m<<16)|(n<<5)|d
fmaxv=lambda d,n:0x6E30F800|(n<<5)|d
fmul_el0=lambda d,n,m:0x4F809000|(m<<16)|(n<<5)|d
frintn=lambda d,n:0x4E218800|(n<<5)|d
fsub=lambda d,n,m:0x4EA0D400|(m<<16)|(n<<5)|d
fcvtns=lambda d,n:0x4E21A800|(n<<5)|d
sqxtn_h=lambda d,n:0x0E614800|(n<<5)|d
sqxtn2_h=lambda d,n:0x4E614800|(n<<5)|d
sqxtn_b=lambda d,n:0x0E214800|(n<<5)|d
sqxtn2_b=lambda d,n:0x4E214800|(n<<5)|d
e('// func quantX2RowNEON(q1, q2 *int8, s *float32, a *float32, nb int, c127, tiny, c256 float32)')
e('TEXT ·quantX2RowNEON(SB), NOSPLIT, $0-52')
e('\tMOVD q1+0(FP), R0\n\tMOVD q2+8(FP), R1\n\tMOVD s+16(FP), R2\n\tMOVD a+24(FP), R3\n\tMOVD nb+32(FP), R4')
e('\tFMOVS c127+40(FP), F28\n\tFMOVS tiny+44(FP), F29\n\tFMOVS c256+48(FP), F30')
e('\tCBZ R4, qdone')
e('qloop:')
e('\tVLD1.P 64(R3), [V0.S4, V1.S4, V2.S4, V3.S4]')
e('\tVLD1.P 64(R3), [V4.S4, V5.S4, V6.S4, V7.S4]')
for i in range(8): W(fabs(8+i,i),'FABS')
for i in range(4): W(fmax(8+i,8+i,12+i),'FMAX')
W(fmax(8,8,10),'FMAX');W(fmax(9,9,11),'FMAX');W(fmax(8,8,9),'FMAX')
W(fmaxv(16,8),'FMAXV S16')
e('\tFDIVS F28, F16, F17 // d = amax/127')
e('\tFDIVS F30, F17, F17 // S = d/256')
e('\tFMOVS.P F17, 4(R2)')
e('\tFMAXS F29, F16, F18\n\tFDIVS F18, F28, F19 // id')
for i in range(8):
    W(fmul_el0(i,i,19),f'FMUL V{i}, V{i}, V19.S[0] (p)')
    W(frintn(8+i,i),f'FRINTN V{8+i} (q1f)')
    W(fsub(i,i,8+i),f'FSUB V{i} = p - q1f')
    W(fmul_el0(i,i,30),f'FMUL V{i} *= 256')
    W(fcvtns(i,i),'FCVTNS q2'); W(fcvtns(8+i,8+i),'FCVTNS q1')
# narrow q1 (V8-V15) -> V24,V25 ; q2 (V0-V7) -> V26,V27
for k in range(4):
    W(sqxtn_h(20+k,8+2*k),'SQXTN');W(sqxtn2_h(20+k,9+2*k),'SQXTN2')
W(sqxtn_b(24,20),'');W(sqxtn2_b(24,21),'');W(sqxtn_b(25,22),'');W(sqxtn2_b(25,23),'')
for k in range(4):
    W(sqxtn_h(20+k,2*k),'SQXTN');W(sqxtn2_h(20+k,1+2*k),'SQXTN2')
W(sqxtn_b(26,20),'');W(sqxtn2_b(26,21),'');W(sqxtn_b(27,22),'');W(sqxtn2_b(27,23),'')
# store 8-byte chunks: V24 = k0..15 (chunks 0,1), V25 = k16..31 (chunks 2,3)
for (reg,base) in ((24,'R0'),(26,'R1')):
    e(f'\tVMOV V{reg}.D[0], R5\n\tVMOV V{reg}.D[1], R6\n\tVMOV V{reg+1}.D[0], R7\n\tVMOV V{reg+1}.D[1], R8')
    e(f'\tMOVD R5, ({base})\n\tMOVD R6, 16({base})\n\tMOVD R7, 32({base})\n\tMOVD R8, 48({base})\n\tADD $64, {base}, {base}')
e('\tSUB $1, R4, R4\n\tCBNZ R4, qloop')
e('qdone:\n\tRET')
open('q8p_i8mm_arm64.s','w').write('\n'.join(L)+'\n')
