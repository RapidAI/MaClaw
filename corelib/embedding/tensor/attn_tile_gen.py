#!/usr/bin/env python3
# Generates attn_tile_arm64.s: 4-query tiled attention kernels (head_dim 128).
L=[];e=L.append
W=lambda x,c='': e(f'\tWORD ${x:#08x} // {c}')
fmla=lambda d,n,m:0x4E20CC00|(m<<16)|(n<<5)|d
fmla_el=lambda d,n,m,i:0x4F801000|((i&1)<<21)|(m<<16)|((i>>1)<<11)|(n<<5)|d
faddp=lambda d,n,m:0x6E20D400|(m<<16)|(n<<5)|d
fmul=lambda d,n,m:0x6E20DC00|(m<<16)|(n<<5)|d
fmax=lambda d,n,m:0x4E20F400|(m<<16)|(n<<5)|d
fmaxv=lambda d,n:0x6E30F800|(n<<5)|d
fsub=lambda d,n,m:0x4EA0D400|(m<<16)|(n<<5)|d
fadd=lambda d,n,m:0x4E20D400|(m<<16)|(n<<5)|d
fcvtzs=lambda d,n:0x4EA1B800|(n<<5)|d
fcmge=lambda d,n,m:0x6E20E400|(m<<16)|(n<<5)|d
vand=lambda d,n,m:0x4E201C00|(m<<16)|(n<<5)|d
e('//go:build arm64\n\n// Code generated by attn_tile_gen.py; DO NOT EDIT.\n\n#include "textflag.h"\n')
# QK: out[r*ldS + s] = scale*dot(q_r, k_s), r<4, s<nblk*4
e('// func attnQK4x4NEON(out *float32, ldSBytes int, q *float32, qStrideBytes int, k *float32, kStrideBytes int, nblk int, scale float32)')
e('TEXT ·attnQK4x4NEON(SB), NOSPLIT, $0-60')
e('\tMOVD out+0(FP), R0\n\tMOVD ldSBytes+8(FP), R1\n\tMOVD q+16(FP), R2\n\tMOVD qStrideBytes+24(FP), R3\n\tMOVD k+32(FP), R4\n\tMOVD kStrideBytes+40(FP), R5\n\tMOVD nblk+48(FP), R6')
e('\tFMOVS scale+56(FP), F31\n\tVDUP V31.S[0], V31.S4')
e('\tLSL $2, R5, R15 // 4 key rows')
e('qkblk:')
for i in range(16): e(f'\tVEOR V{i}.B16, V{i}.B16, V{i}.B16')
e('\tMOVD R2, R7\n\tADD R3, R7, R8\n\tADD R3, R8, R9\n\tADD R3, R9, R10')
e('\tMOVD R4, R11\n\tADD R5, R11, R12\n\tADD R5, R12, R13\n\tADD R5, R13, R14')
e('\tMOVD $32, R16')
e('qkd:')
for r,R in enumerate(['R7','R8','R9','R10']): e(f'\tFMOVQ.P 16({R}), F{16+r}')
for s,R in enumerate(['R11','R12','R13','R14']): e(f'\tFMOVQ.P 16({R}), F{20+s}')
for r in range(4):
    for s in range(4):
        W(fmla(r*4+s,16+r,20+s),f'acc[{r}][{s}]')
e('\tSUB $1, R16, R16\n\tCBNZ R16, qkd')
e('\tMOVD R0, R7')
for r in range(4):
    a=r*4
    W(faddp(24,a,a+1));W(faddp(25,a+2,a+3));W(faddp(26,24,25));W(fmul(26,26,31))
    e(f'\tFMOVQ F26, (R7)\n\tADD R1, R7, R7')
e('\tADD $16, R0, R0\n\tADD R15, R4, R4\n\tSUB $1, R6, R6\n\tCBNZ R6, qkblk\n\tRET\n')
# PV: out[r][0:128] = sum_s pt[s*4+r] * v[s]
e('// func attnPV4NEON(out *float32, outStrideBytes int, pt *float32, v *float32, vStrideBytes int, n int)')
e('TEXT ·attnPV4NEON(SB), NOSPLIT, $0-48')
e('\tMOVD out+0(FP), R0\n\tMOVD outStrideBytes+8(FP), R1\n\tMOVD v+24(FP), R3\n\tMOVD vStrideBytes+32(FP), R4')
e('\tMOVD $0, R9 // dim group byte offset (64 B = 16 floats)')
e('pvg:')
for i in range(16): e(f'\tVEOR V{i}.B16, V{i}.B16, V{i}.B16')
e('\tMOVD pt+16(FP), R2\n\tMOVD n+40(FP), R5\n\tADD R9, R3, R6')
e('pvs:')
e('\tFMOVQ.P 16(R2), F20')
e('\tVLD1 (R6), [V16.S4, V17.S4, V18.S4, V19.S4]')
e('\tADD R4, R6, R6')
for r in range(4):
    for g in range(4):
        W(fmla_el(r*4+g,16+g,20,r),f'out[{r}][{g}] += v{g}*p[{r}]')
e('\tSUB $1, R5, R5\n\tCBNZ R5, pvs')
e('\tADD R9, R0, R7')
for r in range(4):
    e(f'\tVST1 [V{4*r}.S4, V{4*r+1}.S4, V{4*r+2}.S4, V{4*r+3}.S4], (R7)\n\tADD R1, R7, R7')
e('\tADD $64, R9, R9\n\tCMP $512, R9\n\tBLT pvg\n\tRET\n')
# softmax (Schraudolph exp, same constants as fastExp): x in place -> exp(x-max); returns sum. n multiple of 4.
e('// func softmaxExp4NEON(x *float32, n int, max, a, b, neg88 float32) float32')
e('TEXT ·softmaxExp4NEON(SB), NOSPLIT, $0-36')
e('\tMOVD x+0(FP), R0\n\tMOVD n+8(FP), R1')
for i,nm in enumerate(['max','a','b','neg88']):
    e(f'\tFMOVS {nm}+{16+4*i}(FP), F{24+i}\n\tVDUP V{24+i}.S[0], V{24+i}.S4')
e('\tVEOR V0.B16, V0.B16, V0.B16')
e('smx:')
e('\tVLD1 (R0), [V1.S4]')
W(fsub(1,1,24),'x-max')
W(fcmge(2,1,27),'mask x>=-88')
e('\tVMOV V26.B16, V3.B16')
W(fmla(3,1,25),'b + a*x (fused, as Go on arm64)')
W(fcvtzs(3,3),'trunc')
W(vand(3,3,2),'zero if < -88')
W(fadd(0,0,3),'sum')
e('\tVST1.P [V3.S4], 16(R0)')
e('\tSUB $4, R1, R1\n\tCBNZ R1, smx')
W(faddp(0,0,0));W(0x7E30D800|(0<<5)|0,'FADDP S0')
e('\tFMOVS F0, ret+32(FP)\n\tRET')
open('attn_tile_arm64.s','w').write('\n'.join(L)+'\n')
