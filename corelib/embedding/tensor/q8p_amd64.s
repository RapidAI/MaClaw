// func q8pQuantizeAVX512(q *int8, s *float32, c *int32, a *float32, nBlocks int)
// Per 32-float block: d = amax/127, q = RNE(x·(127/max(amax,1e-30))),
// c = −128·Σq. Bit-identical to quantizeQ8ActGo.
TEXT ·q8pQuantizeAVX512(SB), NOSPLIT, $0-40
	MOVQ q+0(FP), DI
	MOVQ s+8(FP), BX
	MOVQ c+16(FP), DX
	MOVQ a+24(FP), SI
	MOVQ nBlocks+32(FP), CX
	MOVL $0x7fffffff, AX
	VPBROADCASTD AX, Z31
	MOVL $0x42fe0000, AX
	VMOVD AX, X30
	MOVL $0x0da24260, AX
	VMOVD AX, X29
qloop:
	VMOVUPS (SI), Z0
	VMOVUPS 64(SI), Z1
	VANDPS Z31, Z0, Z2
	VANDPS Z31, Z1, Z3
	VMAXPS Z3, Z2, Z2
	VEXTRACTF64X4 $1, Z2, Y3
	VMAXPS Y3, Y2, Y2
	VEXTRACTF128 $1, Y2, X3
	VMAXPS X3, X2, X2
	VPERMILPS $0x4e, X2, X3
	VMAXPS X3, X2, X2
	VPERMILPS $0xb1, X2, X3
	VMAXPS X3, X2, X2
	VDIVSS X30, X2, X4
	VMOVSS X4, (BX)
	VMAXSS X29, X2, X2
	VDIVSS X2, X30, X5
	VBROADCASTSS X5, Z5
	VMULPS Z5, Z0, Z0
	VMULPS Z5, Z1, Z1
	VCVTPS2DQ Z0, Z0
	VCVTPS2DQ Z1, Z1
	VPMOVSDB Z0, X6
	VPMOVSDB Z1, X7
	VMOVDQU X6, (DI)
	VMOVDQU X7, 16(DI)
	VPADDD Z1, Z0, Z0
	VEXTRACTI64X4 $1, Z0, Y1
	VPADDD Y1, Y0, Y0
	VEXTRACTI128 $1, Y0, X1
	VPADDD X1, X0, X0
	VPSHUFD $0x4e, X0, X1
	VPADDD X1, X0, X0
	VPSHUFD $0xb1, X0, X1
	VPADDD X1, X0, X0
	VMOVD X0, AX
	IMULL $-128, AX
	MOVL AX, (DX)
	ADDQ $128, SI
	ADDQ $32, DI
	ADDQ $4, BX
	ADDQ $4, DX
	DECQ CX
	JNZ qloop
	VZEROUPPER
	RET

// func attnWSum128AVX512(out *float32, w *float32, v *float32, rows, strideBytes int, scale float32)
// out[0:128] = scale · Σ_r w[r]·v[r*stride : r*stride+128]
TEXT ·attnWSum128AVX512(SB), NOSPLIT, $0-44
	MOVQ out+0(FP), DI
	MOVQ w+8(FP), SI
	MOVQ v+16(FP), BX
	MOVQ rows+24(FP), CX
	MOVQ strideBytes+32(FP), DX
	VBROADCASTSS scale+40(FP), Z16
	VPXORD Z0, Z0, Z0
	VPXORD Z1, Z1, Z1
	VPXORD Z2, Z2, Z2
	VPXORD Z3, Z3, Z3
	VPXORD Z4, Z4, Z4
	VPXORD Z5, Z5, Z5
	VPXORD Z6, Z6, Z6
	VPXORD Z7, Z7, Z7
	TESTQ CX, CX
	JLE wdone
wloop:
	VBROADCASTSS (SI), Z17
	VFMADD231PS (BX), Z17, Z0
	VFMADD231PS 64(BX), Z17, Z1
	VFMADD231PS 128(BX), Z17, Z2
	VFMADD231PS 192(BX), Z17, Z3
	VFMADD231PS 256(BX), Z17, Z4
	VFMADD231PS 320(BX), Z17, Z5
	VFMADD231PS 384(BX), Z17, Z6
	VFMADD231PS 448(BX), Z17, Z7
	ADDQ $4, SI
	ADDQ DX, BX
	DECQ CX
	JNZ wloop
wdone:
	VMULPS Z16, Z0, Z0
	VMULPS Z16, Z1, Z1
	VMULPS Z16, Z2, Z2
	VMULPS Z16, Z3, Z3
	VMULPS Z16, Z4, Z4
	VMULPS Z16, Z5, Z5
	VMULPS Z16, Z6, Z6
	VMULPS Z16, Z7, Z7
	VMOVUPS Z0, (DI)
	VMOVUPS Z1, 64(DI)
	VMOVUPS Z2, 128(DI)
	VMOVUPS Z3, 192(DI)
	VMOVUPS Z4, 256(DI)
	VMOVUPS Z5, 320(DI)
	VMOVUPS Z6, 384(DI)
	VMOVUPS Z7, 448(DI)
	VZEROUPPER
	RET

// ---- AVX-VNNI (256-bit VEX VPDPBUSD) + AVX2 (VPMADDUBSW sign-trick) ----
// Same u8=w+128 weight layout as AVX-512. 4×32 tile = four 8-col YMM groups.
// VEX VPDPBUSD is hand-encoded (Go assembler only emits EVEX).

// func q8pTile4x32AVXVNNI(out *float32, aq *int8, kStride int, ac *int32, as *float32, nbStride int, qb *byte, sb *float32, nb int)
TEXT ·q8pTile4x32AVXVNNI(SB), NOSPLIT, $0-72
	MOVQ out+0(FP), DI
	MOVQ nbStride+40(FP), CX
	LEAQ (CX)(CX*2), DX
	MOVQ $0, R14
vnni_grp:
	MOVQ aq+8(FP), SI
	MOVQ kStride+16(FP), R8
	LEAQ (SI)(R8*1), R9
	LEAQ (R9)(R8*1), R10
	LEAQ (R10)(R8*1), R11
	MOVQ ac+24(FP), AX
	MOVQ as+32(FP), BX
	MOVQ R14, R8
	SHLQ $5, R8
	MOVQ qb+48(FP), R12
	ADDQ R8, R12
	MOVQ sb+56(FP), R13
	ADDQ R8, R13
	MOVQ nb+64(FP), R15
	VXORPS Y12, Y12, Y12
	VXORPS Y13, Y13, Y13
	VXORPS Y14, Y14, Y14
	VXORPS Y15, Y15, Y15
vnni_blk:
	VPBROADCASTD (AX), Y0
	VPBROADCASTD (AX)(CX*1), Y1
	VPBROADCASTD (AX)(CX*2), Y2
	VPBROADCASTD (AX)(DX*1), Y3
	MOVQ $8, R8
vnni_k:
	VMOVDQU (R12), Y8

	VPBROADCASTD (SI), Y9
	BYTE $0xC4; BYTE $0xc2; BYTE $0x3d; BYTE $0x50; BYTE $0xc1	// VPDPBUSD Y0, Y8, Y9
	VPBROADCASTD (R9), Y9
	BYTE $0xC4; BYTE $0xc2; BYTE $0x3d; BYTE $0x50; BYTE $0xc9	// VPDPBUSD Y1, Y8, Y9
	VPBROADCASTD (R10), Y9
	BYTE $0xC4; BYTE $0xc2; BYTE $0x3d; BYTE $0x50; BYTE $0xd1	// VPDPBUSD Y2, Y8, Y9
	VPBROADCASTD (R11), Y9
	BYTE $0xC4; BYTE $0xc2; BYTE $0x3d; BYTE $0x50; BYTE $0xd9	// VPDPBUSD Y3, Y8, Y9
	ADDQ $4, SI
	ADDQ $4, R9
	ADDQ $4, R10
	ADDQ $4, R11
	ADDQ $128, R12
	DECQ R8
	JNZ vnni_k
	VMOVUPS (R13), Y8
	VBROADCASTSS (BX), Y9
	VMULPS Y9, Y8, Y10
	VCVTDQ2PS Y0, Y0
	VFMADD231PS Y10, Y0, Y12
	VBROADCASTSS (BX)(CX*1), Y9
	VMULPS Y9, Y8, Y10
	VCVTDQ2PS Y1, Y1
	VFMADD231PS Y10, Y1, Y13
	VBROADCASTSS (BX)(CX*2), Y9
	VMULPS Y9, Y8, Y10
	VCVTDQ2PS Y2, Y2
	VFMADD231PS Y10, Y2, Y14
	VBROADCASTSS (BX)(DX*1), Y9
	VMULPS Y9, Y8, Y10
	VCVTDQ2PS Y3, Y3
	VFMADD231PS Y10, Y3, Y15
	ADDQ $4, AX
	ADDQ $4, BX
	ADDQ $128, R13
	DECQ R15
	JNZ vnni_blk
	MOVQ R14, R8
	SHLQ $5, R8
	MOVQ out+0(FP), DI
	ADDQ R8, DI
	VMOVUPS Y12, 0(DI)
	VMOVUPS Y13, 128(DI)
	VMOVUPS Y14, 256(DI)
	VMOVUPS Y15, 384(DI)
	INCQ R14
	CMPQ R14, $4
	JLT vnni_grp
	VZEROUPPER
	RET

// func q8pTile4x32AVX2(...) — VPMADDUBSW+VPMADDWD with abs(w)/sign(a) trick.
// Convert u8=w+128 → s8 via XOR 0x80; VPABSB → |w|; VPSIGNB applies sign(w)
// to activations. |w|,|a|≤127 so 2·127·127=32258 fits in int16 (no saturation).
// Accumulators start at 0 (true s8×s8; C correction not applied).
TEXT ·q8pTile4x32AVX2(SB), NOSPLIT, $0-72
	MOVQ out+0(FP), DI
	MOVQ nbStride+40(FP), CX
	LEAQ (CX)(CX*2), DX
	MOVQ $0x0001000100010001, R8
	MOVQ R8, X10
	VPBROADCASTQ X10, Y10
	MOVQ $0x8080808080808080, R8
	MOVQ R8, X11
	VPBROADCASTQ X11, Y11
	MOVQ $0, R14
avx2_grp:
	MOVQ aq+8(FP), SI
	MOVQ kStride+16(FP), R8
	LEAQ (SI)(R8*1), R9
	LEAQ (R9)(R8*1), R10
	LEAQ (R10)(R8*1), R11
	MOVQ as+32(FP), BX
	MOVQ R14, R8
	SHLQ $5, R8
	MOVQ qb+48(FP), R12
	ADDQ R8, R12
	MOVQ sb+56(FP), R13
	ADDQ R8, R13
	MOVQ nb+64(FP), R15
	VXORPS Y12, Y12, Y12
	VXORPS Y13, Y13, Y13
	VXORPS Y14, Y14, Y14
	VXORPS Y15, Y15, Y15
avx2_blk:
	VPXOR Y0, Y0, Y0
	VPXOR Y1, Y1, Y1
	VPXOR Y2, Y2, Y2
	VPXOR Y3, Y3, Y3
	MOVQ $8, R8
avx2_k:
	VMOVDQU (R12), Y4
	VPXOR Y4, Y11, Y5
	VPABSB Y5, Y6

	VPBROADCASTD (SI), Y7
	VPSIGNB Y5, Y7, Y7
	VPMADDUBSW Y7, Y6, Y8
	VPMADDWD Y10, Y8, Y8
	VPADDD Y8, Y0, Y0
	VPBROADCASTD (R9), Y7
	VPSIGNB Y5, Y7, Y7
	VPMADDUBSW Y7, Y6, Y8
	VPMADDWD Y10, Y8, Y8
	VPADDD Y8, Y1, Y1
	VPBROADCASTD (R10), Y7
	VPSIGNB Y5, Y7, Y7
	VPMADDUBSW Y7, Y6, Y8
	VPMADDWD Y10, Y8, Y8
	VPADDD Y8, Y2, Y2
	VPBROADCASTD (R11), Y7
	VPSIGNB Y5, Y7, Y7
	VPMADDUBSW Y7, Y6, Y8
	VPMADDWD Y10, Y8, Y8
	VPADDD Y8, Y3, Y3
	ADDQ $4, SI
	ADDQ $4, R9
	ADDQ $4, R10
	ADDQ $4, R11
	ADDQ $128, R12
	DECQ R8
	JNZ avx2_k
	VMOVUPS (R13), Y4
	VBROADCASTSS (BX), Y5
	VMULPS Y5, Y4, Y6
	VCVTDQ2PS Y0, Y0
	VFMADD231PS Y6, Y0, Y12
	VBROADCASTSS (BX)(CX*1), Y5
	VMULPS Y5, Y4, Y6
	VCVTDQ2PS Y1, Y1
	VFMADD231PS Y6, Y1, Y13
	VBROADCASTSS (BX)(CX*2), Y5
	VMULPS Y5, Y4, Y6
	VCVTDQ2PS Y2, Y2
	VFMADD231PS Y6, Y2, Y14
	VBROADCASTSS (BX)(DX*1), Y5
	VMULPS Y5, Y4, Y6
	VCVTDQ2PS Y3, Y3
	VFMADD231PS Y6, Y3, Y15
	ADDQ $4, BX
	ADDQ $128, R13
	DECQ R15
	JNZ avx2_blk
	MOVQ R14, R8
	SHLQ $5, R8
	MOVQ out+0(FP), DI
	ADDQ R8, DI
	VMOVUPS Y12, 0(DI)
	VMOVUPS Y13, 128(DI)
	VMOVUPS Y14, 256(DI)
	VMOVUPS Y15, 384(DI)
	INCQ R14
	CMPQ R14, $4
	JLT avx2_grp
	VZEROUPPER
	RET

// func q8pQuantizeAVX2(q *int8, s *float32, c *int32, a *float32, nBlocks int)
// Bit-identical to quantizeQ8ActGo / q8pQuantizeAVX512.
TEXT ·q8pQuantizeAVX2(SB), NOSPLIT, $0-40
	MOVQ q+0(FP), DI
	MOVQ s+8(FP), BX
	MOVQ c+16(FP), DX
	MOVQ a+24(FP), SI
	MOVQ nBlocks+32(FP), CX
	MOVL $0x7fffffff, AX
	VMOVD AX, X15
	VPBROADCASTD X15, Y15
	MOVL $0x42fe0000, AX
	VMOVD AX, X14
	MOVL $0x0da24260, AX
	VMOVD AX, X13
q2loop:
	VMOVUPS (SI), Y0
	VMOVUPS 32(SI), Y1
	VMOVUPS 64(SI), Y2
	VMOVUPS 96(SI), Y3
	VANDPS Y15, Y0, Y4
	VANDPS Y15, Y1, Y5
	VMAXPS Y5, Y4, Y4
	VANDPS Y15, Y2, Y5
	VMAXPS Y5, Y4, Y4
	VANDPS Y15, Y3, Y5
	VMAXPS Y5, Y4, Y4
	VEXTRACTF128 $1, Y4, X5
	VMAXPS X5, X4, X4
	VPERMILPS $0x4e, X4, X5
	VMAXPS X5, X4, X4
	VPERMILPS $0xb1, X4, X5
	VMAXPS X5, X4, X4
	VDIVSS X14, X4, X6
	VMOVSS X6, (BX)
	VMAXSS X13, X4, X4
	VDIVSS X4, X14, X7
	VBROADCASTSS X7, Y7
	VMULPS Y7, Y0, Y0
	VMULPS Y7, Y1, Y1
	VMULPS Y7, Y2, Y2
	VMULPS Y7, Y3, Y3
	VCVTPS2DQ Y0, Y0
	VCVTPS2DQ Y1, Y1
	VCVTPS2DQ Y2, Y2
	VCVTPS2DQ Y3, Y3
	// sum all 32 int32 → C = -128*sum
	VPADDD Y1, Y0, Y8
	VPADDD Y3, Y2, Y9
	VPADDD Y9, Y8, Y8
	VEXTRACTI128 $1, Y8, X9
	VPADDD X9, X8, X8
	VPSHUFD $0x4e, X8, X9
	VPADDD X9, X8, X8
	VPSHUFD $0xb1, X8, X9
	VPADDD X9, X8, X8
	VMOVD X8, AX
	IMULL $-128, AX
	MOVL AX, (DX)
	// pack i32→i8: two pairs of 16 via PACKSSDW+PERMQ then PACKSSWB+PERMQ
	VPACKSSDW Y1, Y0, Y8
	VPERMQ $0xD8, Y8, Y8
	VPACKSSDW Y3, Y2, Y9
	VPERMQ $0xD8, Y9, Y9
	VPACKSSWB Y9, Y8, Y8
	VPERMQ $0xD8, Y8, Y8
	VMOVDQU Y8, (DI)
	ADDQ $128, SI
	ADDQ $32, DI
	ADDQ $4, BX
	ADDQ $4, DX
	DECQ CX
	JNZ q2loop
	VZEROUPPER
	RET
