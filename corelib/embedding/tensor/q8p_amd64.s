// func q8pQuantizeAVX512(q *int8, s *float32, c *int32, a *float32, nBlocks int)
// Per 32-float block: d = amax/127, q = RNE(x·(127/max(amax,1e-30))),
// c = −128·Σq. Bit-identical to quantizeQ8ActGo.
TEXT ·q8pQuantizeAVX512(SB), NOSPLIT, $0-40
	MOVQ q+0(FP), DI
	MOVQ s+8(FP), BX
	MOVQ c+16(FP), DX
	MOVQ a+24(FP), SI
	MOVQ nBlocks+32(FP), CX
	MOVL $0x7fffffff, AX
	VPBROADCASTD AX, Z31
	MOVL $0x42fe0000, AX
	VMOVD AX, X30
	MOVL $0x0da24260, AX
	VMOVD AX, X29
qloop:
	VMOVUPS (SI), Z0
	VMOVUPS 64(SI), Z1
	VANDPS Z31, Z0, Z2
	VANDPS Z31, Z1, Z3
	VMAXPS Z3, Z2, Z2
	VEXTRACTF64X4 $1, Z2, Y3
	VMAXPS Y3, Y2, Y2
	VEXTRACTF128 $1, Y2, X3
	VMAXPS X3, X2, X2
	VPERMILPS $0x4e, X2, X3
	VMAXPS X3, X2, X2
	VPERMILPS $0xb1, X2, X3
	VMAXPS X3, X2, X2
	VDIVSS X30, X2, X4
	VMOVSS X4, (BX)
	VMAXSS X29, X2, X2
	VDIVSS X2, X30, X5
	VBROADCASTSS X5, Z5
	VMULPS Z5, Z0, Z0
	VMULPS Z5, Z1, Z1
	VCVTPS2DQ Z0, Z0
	VCVTPS2DQ Z1, Z1
	VPMOVSDB Z0, X6
	VPMOVSDB Z1, X7
	VMOVDQU X6, (DI)
	VMOVDQU X7, 16(DI)
	VPADDD Z1, Z0, Z0
	VEXTRACTI64X4 $1, Z0, Y1
	VPADDD Y1, Y0, Y0
	VEXTRACTI128 $1, Y0, X1
	VPADDD X1, X0, X0
	VPSHUFD $0x4e, X0, X1
	VPADDD X1, X0, X0
	VPSHUFD $0xb1, X0, X1
	VPADDD X1, X0, X0
	VMOVD X0, AX
	IMULL $-128, AX
	MOVL AX, (DX)
	ADDQ $128, SI
	ADDQ $32, DI
	ADDQ $4, BX
	ADDQ $4, DX
	DECQ CX
	JNZ qloop
	VZEROUPPER
	RET
