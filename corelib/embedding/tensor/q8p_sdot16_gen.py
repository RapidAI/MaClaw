#!/usr/bin/env python3
# Generates q8p_sdot16_arm64.s (4 rows x 16 cols SDOT-by-element tile).
L=[]
e=L.append
def sdot_el(d,n,m,idx):
    H,Lb=(idx>>1)&1, idx&1
    return 0x4F80E000|(Lb<<21)|(m<<16)|(H<<11)|(n<<5)|d
def fmul_el0(d,n,m): return 0x4F809000|(m<<16)|(n<<5)|d
def scvtf(d,n): return 0x4E21D800|(n<<5)|d
def fmla(d,n,m): return 0x4E20CC00|(m<<16)|(n<<5)|d
e('//go:build arm64\n\n// Code generated by gen/q8p_sdot16_gen.py; DO NOT EDIT.\n\n#include "textflag.h"\n')
e('// func q8pTile4x16SDOT(out *float32, aq *int8, kStride int, as *float32, nbStride int, qb *byte, sb *float32, nb int)')
e('// out: 4 rows x 16 floats at row stride 32 floats, accumulated (+=).')
e('// qb/sb point at the column half (qb+64*h, sb+16*h) of a 32-col panel.')
e('// Regs: V0-V15 int32 acc [m*4+g]; V16-V23 act (row m: V16+2m, V17+2m);')
e('// V24-V27 weights / col scales; V28-V31 row scales.')
e('TEXT ·q8pTile4x16SDOT(SB), NOSPLIT, $0-64')
e('\tMOVD out+0(FP), R0\n\tMOVD aq+8(FP), R1\n\tMOVD kStride+16(FP), R2\n\tMOVD as+24(FP), R3\n\tMOVD nbStride+32(FP), R4\n\tMOVD qb+40(FP), R5\n\tMOVD sb+48(FP), R6\n\tMOVD nb+56(FP), R7')
e('\tADD R2, R1, R8\n\tADD R2, R8, R9\n\tADD R2, R9, R10')
e('\tADD R4, R3, R11\n\tADD R4, R11, R12\n\tADD R4, R12, R13')
e('\tADD $128, R0, R14\n\tADD $128, R14, R15\n\tADD $128, R15, R16')
for i in range(16): e(f'\tVEOR V{i}.B16, V{i}.B16, V{i}.B16')
e('blk:')
for m,r in enumerate(['R1','R8','R9','R10']):
    e(f'\tVLD1.P 32({r}), [V{16+2*m}.B16, V{17+2*m}.B16]')
for j in range(8):
    e('\tVLD1 (R5), [V24.B16, V25.B16, V26.B16, V27.B16]')
    e('\tADD $128, R5, R5')
    for m in range(4):
        for g in range(4):
            e(f'\tWORD ${sdot_el(m*4+g,24+g,16+2*m+j//4,j%4):#08x} // SDOT V{m*4+g}.4S, V{24+g}.16B, V{16+2*m+j//4}.4B[{j%4}]')
e('\tVLD1 (R6), [V24.S4, V25.S4, V26.S4, V27.S4]')
e('\tADD $128, R6, R6')
for m,r in enumerate(['R3','R11','R12','R13']):
    e(f'\tFMOVS.P 4({r}), F{28+m}')
for m,r in enumerate(['R0','R14','R15','R16']):
    e(f'\tVLD1 ({r}), [V16.S4, V17.S4, V18.S4, V19.S4]')
    for g in range(4):
        a=m*4+g
        e(f'\tWORD ${fmul_el0(20+g,24+g,28+m):#08x} // FMUL V{20+g}.4S, V{24+g}.4S, V{28+m}.S[0]')
        e(f'\tWORD ${scvtf(a,a):#08x} // SCVTF V{a}.4S')
        e(f'\tWORD ${fmla(16+g,a,20+g):#08x} // FMLA V{16+g}.4S, V{a}.4S, V{20+g}.4S')
        e(f'\tVEOR V{a}.B16, V{a}.B16, V{a}.B16')
    e(f'\tVST1 [V16.S4, V17.S4, V18.S4, V19.S4], ({r})')
e('\tSUB $1, R7, R7\n\tCBNZ R7, blk\n\tRET')
open('q8p_sdot16_arm64.s','w').write('\n'.join(L)+'\n')
