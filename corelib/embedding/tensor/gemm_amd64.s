// func multiDot4AVX2(out *[4]float32, a, b *float32, K int)
//
// out[i] = sum_k a[i*K + k] * b[k]  for i in 0..3
// a is contiguous [4][K], b is [K].
//
// Frame:
//   out  +0
//   a    +8
//   b    +16
//   K    +24
TEXT ·multiDot4AVX2(SB), NOSPLIT, $0-32
	MOVQ out+0(FP), R11
	MOVQ a+8(FP), SI
	MOVQ b+16(FP), DI
	MOVQ K+24(FP), CX

	// Bytes per row = K * 4
	MOVQ CX, AX
	SHLQ $2, AX

	// Row bases
	MOVQ SI, R8
	LEAQ (SI)(AX*1), R9
	LEAQ (R9)(AX*1), R10
	LEAQ (R10)(AX*1), DX

	VXORPS Y0, Y0, Y0
	VXORPS Y1, Y1, Y1
	VXORPS Y2, Y2, Y2
	VXORPS Y3, Y3, Y3

	MOVQ CX, R12
	SHRQ $3, R12               // K/8
	TESTQ R12, R12
	JZ   hsum

	// Dual-chunk when (K/8) even
	MOVQ R12, R13
	SHRQ $1, R13
	TESTQ R13, R13
	JZ   loop8_one

loop16:
	PREFETCHT0 128(DI)
	VMOVUPS (DI), Y4
	VMOVUPS (R8), Y5
	VFMADD231PS Y5, Y4, Y0
	VMOVUPS (R9), Y5
	VFMADD231PS Y5, Y4, Y1
	VMOVUPS (R10), Y5
	VFMADD231PS Y5, Y4, Y2
	VMOVUPS (DX), Y5
	VFMADD231PS Y5, Y4, Y3

	VMOVUPS 32(DI), Y4
	VMOVUPS 32(R8), Y5
	VFMADD231PS Y5, Y4, Y0
	VMOVUPS 32(R9), Y5
	VFMADD231PS Y5, Y4, Y1
	VMOVUPS 32(R10), Y5
	VFMADD231PS Y5, Y4, Y2
	VMOVUPS 32(DX), Y5
	VFMADD231PS Y5, Y4, Y3

	ADDQ $64, DI
	ADDQ $64, R8
	ADDQ $64, R9
	ADDQ $64, R10
	ADDQ $64, DX
	DECQ R13
	JNZ  loop16

	MOVQ CX, R12
	SHRQ $3, R12
	ANDQ $1, R12
	JZ   hsum

loop8_one:
loop8:
	PREFETCHT0 64(DI)
	VMOVUPS (DI), Y4
	VMOVUPS (R8), Y5
	VFMADD231PS Y5, Y4, Y0
	VMOVUPS (R9), Y5
	VFMADD231PS Y5, Y4, Y1
	VMOVUPS (R10), Y5
	VFMADD231PS Y5, Y4, Y2
	VMOVUPS (DX), Y5
	VFMADD231PS Y5, Y4, Y3

	ADDQ $32, DI
	ADDQ $32, R8
	ADDQ $32, R9
	ADDQ $32, R10
	ADDQ $32, DX
	DECQ R12
	JNZ  loop8

hsum:
	VEXTRACTF128 $1, Y0, X4
	VADDPS X0, X4, X0
	VSHUFPD $1, X0, X0, X15
	VADDPS X0, X15, X0
	VMOVSHDUP X0, X15
	VADDSS X0, X15, X0
	MOVSS X0, (R11)

	VEXTRACTF128 $1, Y1, X4
	VADDPS X1, X4, X1
	VSHUFPD $1, X1, X1, X15
	VADDPS X1, X15, X1
	VMOVSHDUP X1, X15
	VADDSS X1, X15, X1
	MOVSS X1, 4(R11)

	VEXTRACTF128 $1, Y2, X4
	VADDPS X2, X4, X2
	VSHUFPD $1, X2, X2, X15
	VADDPS X2, X15, X2
	VMOVSHDUP X2, X15
	VADDSS X2, X15, X2
	MOVSS X2, 8(R11)

	VEXTRACTF128 $1, Y3, X4
	VADDPS X3, X4, X3
	VSHUFPD $1, X3, X3, X15
	VADDPS X3, X15, X3
	VMOVSHDUP X3, X15
	VADDSS X3, X15, X3
	MOVSS X3, 12(R11)

	// Scalar tail K%8
	MOVQ K+24(FP), CX
	MOVQ CX, R12
	ANDQ $7, R12
	JZ   done

	// Reload bases, skip (K&^7) elements
	MOVQ a+8(FP), SI
	MOVQ b+16(FP), DI
	MOVQ CX, AX
	SHLQ $2, AX               // row stride bytes
	MOVQ CX, R13
	ANDQ $~7, R13
	SHLQ $2, R13              // byte offset into each row

	ADDQ R13, DI

	MOVQ SI, R8
	ADDQ R13, R8
	LEAQ (SI)(AX*1), R9
	ADDQ R13, R9
	LEAQ (SI)(AX*2), R10
	ADDQ R13, R10
	// row3 = SI + 3*AX
	MOVQ AX, DX
	ADDQ AX, DX
	ADDQ AX, DX
	ADDQ SI, DX
	ADDQ R13, DX

tail:
	MOVSS (DI), X4
	MOVSS (R8), X5
	MULSS X4, X5
	ADDSS (R11), X5
	MOVSS X5, (R11)

	MOVSS (R9), X5
	MULSS X4, X5
	ADDSS 4(R11), X5
	MOVSS X5, 4(R11)

	MOVSS (R10), X5
	MULSS X4, X5
	ADDSS 8(R11), X5
	MOVSS X5, 8(R11)

	MOVSS (DX), X5
	MULSS X4, X5
	ADDSS 12(R11), X5
	MOVSS X5, 12(R11)

	ADDQ $4, DI
	ADDQ $4, R8
	ADDQ $4, R9
	ADDQ $4, R10
	ADDQ $4, DX
	DECQ R12
	JNZ  tail

done:
	VZEROUPPER
	RET

// func multiDot4AVX2K512(out *[4]float32, a, b *float32)
