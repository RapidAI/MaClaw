// func multiDot8AVX2(out *[8]float32, a, b *float32, K int)
// 8 A rows x 1 B: B loaded once per chunk into 8 FMA chains.
// All 8 row bases stay in GP registers (no stack spills).
// Dual-chunk (16 floats) when K/16 > 0 for fewer loop branches.
// Frame: out+0, a+8, b+16, K+24
// Registers: R8,R9,R10,DX,SI,BX,R12,R13 = row0..7; R11=out; DI=b; R14=counter
TEXT ·multiDot8AVX2(SB), NOSPLIT, $0-32
	MOVQ out+0(FP), R11
	MOVQ a+8(FP), SI
	MOVQ b+16(FP), DI
	MOVQ K+24(FP), CX

	MOVQ CX, AX
	SHLQ $2, AX               // row stride bytes

	// Row bases all in-register
	MOVQ SI, R8
	LEAQ (SI)(AX*1), R9
	LEAQ (R9)(AX*1), R10
	LEAQ (R10)(AX*1), DX
	LEAQ (DX)(AX*1), SI       // row4 (reuse SI)
	LEAQ (SI)(AX*1), BX       // row5
	LEAQ (BX)(AX*1), R12      // row6
	LEAQ (R12)(AX*1), R13     // row7

	VXORPS Y0, Y0, Y0
	VXORPS Y1, Y1, Y1
	VXORPS Y2, Y2, Y2
	VXORPS Y3, Y3, Y3
	VXORPS Y4, Y4, Y4
	VXORPS Y5, Y5, Y5
	VXORPS Y6, Y6, Y6
	VXORPS Y7, Y7, Y7

	MOVQ CX, R14
	SHRQ $4, R14               // K/16 dual-chunk count
	TESTQ R14, R14
	JZ   md8_single

md8_loop16:
	PREFETCHT0 128(DI)
	// chunk 0
	VMOVUPS (DI), Y8
	VMOVUPS (R8), Y9
	VFMADD231PS Y9, Y8, Y0
	VMOVUPS (R9), Y9
	VFMADD231PS Y9, Y8, Y1
	VMOVUPS (R10), Y9
	VFMADD231PS Y9, Y8, Y2
	VMOVUPS (DX), Y9
	VFMADD231PS Y9, Y8, Y3
	VMOVUPS (SI), Y9
	VFMADD231PS Y9, Y8, Y4
	VMOVUPS (BX), Y9
	VFMADD231PS Y9, Y8, Y5
	VMOVUPS (R12), Y9
	VFMADD231PS Y9, Y8, Y6
	VMOVUPS (R13), Y9
	VFMADD231PS Y9, Y8, Y7
	// chunk 1
	VMOVUPS 32(DI), Y8
	VMOVUPS 32(R8), Y9
	VFMADD231PS Y9, Y8, Y0
	VMOVUPS 32(R9), Y9
	VFMADD231PS Y9, Y8, Y1
	VMOVUPS 32(R10), Y9
	VFMADD231PS Y9, Y8, Y2
	VMOVUPS 32(DX), Y9
	VFMADD231PS Y9, Y8, Y3
	VMOVUPS 32(SI), Y9
	VFMADD231PS Y9, Y8, Y4
	VMOVUPS 32(BX), Y9
	VFMADD231PS Y9, Y8, Y5
	VMOVUPS 32(R12), Y9
	VFMADD231PS Y9, Y8, Y6
	VMOVUPS 32(R13), Y9
	VFMADD231PS Y9, Y8, Y7

	ADDQ $64, DI
	ADDQ $64, R8
	ADDQ $64, R9
	ADDQ $64, R10
	ADDQ $64, DX
	ADDQ $64, SI
	ADDQ $64, BX
	ADDQ $64, R12
	ADDQ $64, R13
	DECQ R14
	JNZ  md8_loop16

	// leftover single 8-float chunk when (K/8) odd
	MOVQ CX, R14
	SHRQ $3, R14
	ANDQ $1, R14
	JZ   md8_hsum

md8_single:
	// R14 = remaining 8-float chunks (1 leftover or full K/8 when K<16)
	TESTQ R14, R14
	JNZ  md8_loop8
	// when entered via JZ md8_single with R14==0 from K/16==0: recompute K/8
	MOVQ CX, R14
	SHRQ $3, R14
	TESTQ R14, R14
	JZ   md8_hsum

md8_loop8:
	PREFETCHT0 64(DI)
	VMOVUPS (DI), Y8
	VMOVUPS (R8), Y9
	VFMADD231PS Y9, Y8, Y0
	VMOVUPS (R9), Y9
	VFMADD231PS Y9, Y8, Y1
	VMOVUPS (R10), Y9
	VFMADD231PS Y9, Y8, Y2
	VMOVUPS (DX), Y9
	VFMADD231PS Y9, Y8, Y3
	VMOVUPS (SI), Y9
	VFMADD231PS Y9, Y8, Y4
	VMOVUPS (BX), Y9
	VFMADD231PS Y9, Y8, Y5
	VMOVUPS (R12), Y9
	VFMADD231PS Y9, Y8, Y6
	VMOVUPS (R13), Y9
	VFMADD231PS Y9, Y8, Y7

	ADDQ $32, DI
	ADDQ $32, R8
	ADDQ $32, R9
	ADDQ $32, R10
	ADDQ $32, DX
	ADDQ $32, SI
	ADDQ $32, BX
	ADDQ $32, R12
	ADDQ $32, R13
	DECQ R14
	JNZ  md8_loop8

md8_hsum:
	VEXTRACTF128 $1, Y0, X8
	VADDPS X0, X8, X0
	VSHUFPD $1, X0, X0, X15
	VADDPS X0, X15, X0
	VMOVSHDUP X0, X15
	VADDSS X0, X15, X0
	MOVSS X0, (R11)

	VEXTRACTF128 $1, Y1, X8
	VADDPS X1, X8, X1
	VSHUFPD $1, X1, X1, X15
	VADDPS X1, X15, X1
	VMOVSHDUP X1, X15
	VADDSS X1, X15, X1
	MOVSS X1, 4(R11)

	VEXTRACTF128 $1, Y2, X8
	VADDPS X2, X8, X2
	VSHUFPD $1, X2, X2, X15
	VADDPS X2, X15, X2
	VMOVSHDUP X2, X15
	VADDSS X2, X15, X2
	MOVSS X2, 8(R11)

	VEXTRACTF128 $1, Y3, X8
	VADDPS X3, X8, X3
	VSHUFPD $1, X3, X3, X15
	VADDPS X3, X15, X3
	VMOVSHDUP X3, X15
	VADDSS X3, X15, X3
	MOVSS X3, 12(R11)

	VEXTRACTF128 $1, Y4, X8
	VADDPS X4, X8, X4
	VSHUFPD $1, X4, X4, X15
	VADDPS X4, X15, X4
	VMOVSHDUP X4, X15
	VADDSS X4, X15, X4
	MOVSS X4, 16(R11)

	VEXTRACTF128 $1, Y5, X8
	VADDPS X5, X8, X5
	VSHUFPD $1, X5, X5, X15
	VADDPS X5, X15, X5
	VMOVSHDUP X5, X15
	VADDSS X5, X15, X5
	MOVSS X5, 20(R11)

	VEXTRACTF128 $1, Y6, X8
	VADDPS X6, X8, X6
	VSHUFPD $1, X6, X6, X15
	VADDPS X6, X15, X6
	VMOVSHDUP X6, X15
	VADDSS X6, X15, X6
	MOVSS X6, 24(R11)

	VEXTRACTF128 $1, Y7, X8
	VADDPS X7, X8, X7
	VSHUFPD $1, X7, X7, X15
	VADDPS X7, X15, X7
	VMOVSHDUP X7, X15
	VADDSS X7, X15, X7
	MOVSS X7, 28(R11)

	// Scalar tail K%8 — bases already advanced past main loop
	MOVQ K+24(FP), CX
	MOVQ CX, R14
	ANDQ $7, R14
	JZ   md8_done

md8_tail:
	MOVSS (DI), X8
	MOVSS (R8), X9
	MULSS X8, X9
	ADDSS (R11), X9
	MOVSS X9, (R11)
	MOVSS (R9), X9
	MULSS X8, X9
	ADDSS 4(R11), X9
	MOVSS X9, 4(R11)
	MOVSS (R10), X9
	MULSS X8, X9
	ADDSS 8(R11), X9
	MOVSS X9, 8(R11)
	MOVSS (DX), X9
	MULSS X8, X9
	ADDSS 12(R11), X9
	MOVSS X9, 12(R11)
	MOVSS (SI), X9
	MULSS X8, X9
	ADDSS 16(R11), X9
	MOVSS X9, 16(R11)
	MOVSS (BX), X9
	MULSS X8, X9
	ADDSS 20(R11), X9
	MOVSS X9, 20(R11)
	MOVSS (R12), X9
	MULSS X8, X9
	ADDSS 24(R11), X9
	MOVSS X9, 24(R11)
	MOVSS (R13), X9
	MULSS X8, X9
	ADDSS 28(R11), X9
	MOVSS X9, 28(R11)

	ADDQ $4, DI
	ADDQ $4, R8
	ADDQ $4, R9
	ADDQ $4, R10
	ADDQ $4, DX
	ADDQ $4, SI
	ADDQ $4, BX
	ADDQ $4, R12
	ADDQ $4, R13
	DECQ R14
	JNZ  md8_tail

md8_done:
	VZEROUPPER
	RET

// func multiDot4DualBAVX2(out *[8]float32, a, b0, b1 *float32, K int)
//
// out[0:4] = multiDot4(a, b0); out[4:8] = multiDot4(a, b1)
// Loads each A chunk once and FMAs into both B accumulator chains.
// Frame: out+0, a+8, b0+16, b1+24, K+32
TEXT ·multiDot4DualBAVX2(SB), NOSPLIT, $0-40
	MOVQ out+0(FP), R11
	MOVQ a+8(FP), SI
	MOVQ b0+16(FP), DI
	MOVQ b1+24(FP), R15
	MOVQ K+32(FP), CX

	// Row stride bytes = K*4
	MOVQ CX, AX
	SHLQ $2, AX

	// Row bases R8,R9,R10,R12
	MOVQ SI, R8
	LEAQ (SI)(AX*1), R9
	LEAQ (R9)(AX*1), R10
	LEAQ (R10)(AX*1), R12

	// Y0-Y3: dots with b0; Y4-Y7: dots with b1
	VXORPS Y0, Y0, Y0
	VXORPS Y1, Y1, Y1
	VXORPS Y2, Y2, Y2
	VXORPS Y3, Y3, Y3
	VXORPS Y4, Y4, Y4
