// ARM64 NEON WORD encodings (same as q8_arm64.s):
// FMUL  Vd.4S, Vn.4S, Vm.4S  = 0x6E20DC00 | Rm<<16 | Rn<<5 | Rd
// FMLA  Vd.4S, Vn.4S, Vm.4S  = 0x4E20CC00 | Rm<<16 | Rn<<5 | Rd
// SSHLL  Vd.8H, Vn.8B, #0    = 0x0F08A400 | Rn<<5 | Rd
// SSHLL2 Vd.8H, Vn.16B, #0   = 0x4F08A400 | Rn<<5 | Rd
// SSHLL  Vd.4S, Vn.4H, #0    = 0x0F10A400 | Rn<<5 | Rd
// SSHLL2 Vd.4S, Vn.8H, #0    = 0x4F10A400 | Rn<<5 | Rd
// SCVTF  Vd.4S, Vn.4S        = 0x4E21D800 | Rn<<5 | Rd
// FADDP  Vd.4S, Vn.4S, Vm.4S = 0x6E20D400 | Rm<<16 | Rn<<5 | Rd
// FADDP  Sd, Vn.2S            = 0x7E30D800 | Rn<<5 | Rd
// DUP Vd.4S, Vn.S[0]         = 0x4E040400 | Rn<<5 | Rd

// func q8MultiDot4NEON(out *[4]float32, a *float32, K int, data *byte, rowOff, nBlocks int)
//
// out[i] = sum dequant(B_row) * A[i]
// a is contiguous [4][K], K = nBlocks*32.
//
// Frame: out+0, a+8, K+16, data+24, rowOff+32, nBlocks+40
TEXT ·q8MultiDot4NEON(SB), NOSPLIT, $0-48
	MOVD  out+0(FP), R0
	MOVD  a+8(FP), R1
	MOVD  K+16(FP), R4
	MOVD  data+24(FP), R2
	MOVD  rowOff+32(FP), R5
	MOVD  nBlocks+40(FP), R3
	ADD   R5, R2, R2          // R2 = start of Q8 row

	// Row stride bytes = K*4
	LSL   $2, R4, R4

	// Row pointers R5..R8
	MOVD  R1, R5
	ADD   R4, R5, R6
	ADD   R4, R6, R7
	ADD   R4, R7, R8

	// Zero accumulators V0..V3
	VEOR  V0.B16, V0.B16, V0.B16
	VEOR  V1.B16, V1.B16, V1.B16
	VEOR  V2.B16, V2.B16, V2.B16
	VEOR  V3.B16, V3.B16, V3.B16

	CBZ   R3, qmd4_hsum

qmd4_block:
	// --- f16 scale → f32 broadcast into V16 (match q8_arm64.s) ---
	MOVHU (R2), R9
	UBFX  $10, R9, $5, R10    // exponent
	AND   $0x3ff, R9, R11     // mantissa
	CBZ   R10, qmd4_scale0
	ADD   $112, R10, R10
	LSL   $23, R10, R10
	LSL   $13, R11, R11
	ORR   R10, R11, R10
	FMOVS R10, F16
	B     qmd4_scale_ok
qmd4_scale0:
	FMOVS ZR, F16
qmd4_scale_ok:
	// DUP V16.4S, V16.S[0]: Rn=16 Rd=16 = 0x4E040400 | (16<<5) | 16 = 0x4E040610
	WORD  $0x4E040610

	// Load 32 int8 values
	ADD   $2, R2, R9
	VLD1  (R9), [V18.B16, V19.B16]

	// ---- Group 0: bytes[0..3] → V17 dequant ----
	// SSHLL V20.8H, V18.8B, #0: Rn=18 Rd=20 = 0x0F08A400 | (18<<5) | 20 = 0x0F08A654
	WORD  $0x0F08A654
	// SSHLL V17.4S, V20.4H, #0: Rn=20 Rd=17 = 0x0F10A400 | (20<<5) | 17 = 0x0F10A691
	WORD  $0x0F10A691
	// SCVTF V17.4S, V17.4S: Rn=17 Rd=17 = 0x4E21D800 | (17<<5) | 17 = 0x4E21DA31
	WORD  $0x4E21DA31
	// FMUL V17.4S, V16.4S, V17.4S: Rm=17 Rn=16 Rd=17
	// = 0x6E20DC00 | (17<<16) | (16<<5) | 17 = 0x6E31DC00 | 0x200 | 17 = 0x6E31DE11
	WORD  $0x6E31DE11

	VLD1.P 16(R5), [V21.S4]
	// FMLA V0.4S, V21.4S, V17.4S: Rd=0 Rn=21 Rm=17
	// = 0x4E20CC00 | (17<<16) | (21<<5) | 0 = 0x4E31CC00 | 0x2A0 = 0x4E31CEA0
	WORD  $0x4E31CEA0
	VLD1.P 16(R6), [V21.S4]
	// FMLA V1.4S, V21.4S, V17.4S
	WORD  $0x4E31CEA1
	VLD1.P 16(R7), [V21.S4]
	WORD  $0x4E31CEA2
	VLD1.P 16(R8), [V21.S4]
	WORD  $0x4E31CEA3

	// ---- Group 1: bytes[4..7] ----
	// SSHLL2 V17.4S, V20.8H, #0: Rn=20 Rd=17 = 0x4F10A400 | (20<<5) | 17 = 0x4F10A691
	WORD  $0x4F10A691
	WORD  $0x4E21DA31         // SCVTF V17
	WORD  $0x6E31DE11         // FMUL V17 = scale * V17
	VLD1.P 16(R5), [V21.S4]
	WORD  $0x4E31CEA0
	VLD1.P 16(R6), [V21.S4]
	WORD  $0x4E31CEA1
	VLD1.P 16(R7), [V21.S4]
	WORD  $0x4E31CEA2
	VLD1.P 16(R8), [V21.S4]
	WORD  $0x4E31CEA3

	// ---- Group 2: bytes[8..11] ----
	// SSHLL2 V20.8H, V18.16B, #0: Rn=18 Rd=20 = 0x4F08A400 | (18<<5) | 20 = 0x4F08A654
	WORD  $0x4F08A654
	// SSHLL V17.4S, V20.4H, #0
	WORD  $0x0F10A691
	WORD  $0x4E21DA31
	WORD  $0x6E31DE11
	VLD1.P 16(R5), [V21.S4]
	WORD  $0x4E31CEA0
	VLD1.P 16(R6), [V21.S4]
	WORD  $0x4E31CEA1
	VLD1.P 16(R7), [V21.S4]
	WORD  $0x4E31CEA2
	VLD1.P 16(R8), [V21.S4]
	WORD  $0x4E31CEA3

	// ---- Group 3: bytes[12..15] ----
	WORD  $0x4F10A691         // SSHLL2 V17.4S, V20.8H
	WORD  $0x4E21DA31
	WORD  $0x6E31DE11
	VLD1.P 16(R5), [V21.S4]
	WORD  $0x4E31CEA0
	VLD1.P 16(R6), [V21.S4]
	WORD  $0x4E31CEA1
	VLD1.P 16(R7), [V21.S4]
	WORD  $0x4E31CEA2
	VLD1.P 16(R8), [V21.S4]
	WORD  $0x4E31CEA3

	// ---- Group 4: bytes[16..19] from V19 ----
	// SSHLL V20.8H, V19.8B, #0: Rn=19 Rd=20 = 0x0F08A400 | (19<<5) | 20 = 0x0F08A674
	WORD  $0x0F08A674
	WORD  $0x0F10A691         // SSHLL V17.4S, V20.4H
	WORD  $0x4E21DA31
	WORD  $0x6E31DE11
	VLD1.P 16(R5), [V21.S4]
	WORD  $0x4E31CEA0
	VLD1.P 16(R6), [V21.S4]
	WORD  $0x4E31CEA1
	VLD1.P 16(R7), [V21.S4]
	WORD  $0x4E31CEA2
	VLD1.P 16(R8), [V21.S4]
	WORD  $0x4E31CEA3

	// ---- Group 5: bytes[20..23] ----
	WORD  $0x4F10A691
	WORD  $0x4E21DA31
	WORD  $0x6E31DE11
	VLD1.P 16(R5), [V21.S4]
	WORD  $0x4E31CEA0
	VLD1.P 16(R6), [V21.S4]
	WORD  $0x4E31CEA1
	VLD1.P 16(R7), [V21.S4]
	WORD  $0x4E31CEA2
	VLD1.P 16(R8), [V21.S4]
	WORD  $0x4E31CEA3

	// ---- Group 6: bytes[24..27] ----
	// SSHLL2 V20.8H, V19.16B, #0: Rn=19 Rd=20 = 0x4F08A400 | (19<<5) | 20 = 0x4F08A674
	WORD  $0x4F08A674
	WORD  $0x0F10A691
	WORD  $0x4E21DA31
	WORD  $0x6E31DE11
	VLD1.P 16(R5), [V21.S4]
	WORD  $0x4E31CEA0
	VLD1.P 16(R6), [V21.S4]
	WORD  $0x4E31CEA1
	VLD1.P 16(R7), [V21.S4]
	WORD  $0x4E31CEA2
	VLD1.P 16(R8), [V21.S4]
	WORD  $0x4E31CEA3

	// ---- Group 7: bytes[28..31] ----
	WORD  $0x4F10A691
	WORD  $0x4E21DA31
	WORD  $0x6E31DE11
	VLD1.P 16(R5), [V21.S4]
	WORD  $0x4E31CEA0
	VLD1.P 16(R6), [V21.S4]
	WORD  $0x4E31CEA1
	VLD1.P 16(R7), [V21.S4]
	WORD  $0x4E31CEA2
	VLD1.P 16(R8), [V21.S4]
	WORD  $0x4E31CEA3

	// Next Q8 block (+34); A rows already advanced +128 bytes via VLD1.P
	ADD   $34, R2, R2
	SUB   $1, R3, R3
	CBNZ  R3, qmd4_block

qmd4_hsum:
	WORD  $0x6E20D400         // FADDP V0
	WORD  $0x7E30D800
	FMOVS F0, (R0)

	WORD  $0x6E21D421
	WORD  $0x7E30D821
	FMOVS F1, 4(R0)

	WORD  $0x6E22D442
	WORD  $0x7E30D842
	FMOVS F2, 8(R0)

	WORD  $0x6E23D463
	WORD  $0x7E30D863
	FMOVS F3, 12(R0)
	RET

// func q8MultiDot8NEON(out *[8]float32, a *float32, K int, data *byte, rowOff, nBlocks int)
// 8 A rows; dequant B once per group, FMLA into V0..V7.
// Frame: out+0, a+8, K+16, data+24, rowOff+32, nBlocks+40
