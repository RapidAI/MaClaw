	VLD1.P 16(R6), [V21.S4]
	WORD  $0x4E31CEA1         // FMLA V1
	VLD1.P 16(R7), [V21.S4]
	WORD  $0x4E31CEA2
	VLD1.P 16(R8), [V21.S4]
	WORD  $0x4E31CEA3
	VLD1.P 16(R9), [V21.S4]
	WORD  $0x4E31CEA4
	VLD1.P 16(R10), [V21.S4]
	WORD  $0x4E31CEA5
	VLD1.P 16(R11), [V21.S4]
	WORD  $0x4E31CEA6
	VLD1.P 16(R12), [V21.S4]
	WORD  $0x4E31CEA7

	// Group 1
	WORD  $0x4F10A691
	WORD  $0x4E21DA31
	WORD  $0x6E31DE11
	VLD1.P 16(R5), [V21.S4]
	WORD  $0x4E31CEA0
	VLD1.P 16(R6), [V21.S4]
