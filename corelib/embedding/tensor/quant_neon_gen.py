#!/usr/bin/env python3
# Generates quant_neon_arm64.s: Q8_0 activation quantizer (bit-identical to quantizeQ8ActGo for q/s).
L=[];e=L.append
W=lambda x,c: e(f'\tWORD ${x:#08x} // {c}')
fabs=lambda d,n:0x4EA0F800|(n<<5)|d
fmax=lambda d,n,m:0x4E20F400|(m<<16)|(n<<5)|d
fmaxv=lambda d,n:0x6E30F800|(n<<5)|d
fmul_el0=lambda d,n,m:0x4F809000|(m<<16)|(n<<5)|d
fcvtns=lambda d,n:0x4E21A800|(n<<5)|d
sqxtn_h=lambda d,n:0x0E614800|(n<<5)|d
sqxtn2_h=lambda d,n:0x4E614800|(n<<5)|d
sqxtn_b=lambda d,n:0x0E214800|(n<<5)|d
sqxtn2_b=lambda d,n:0x4E214800|(n<<5)|d
e('//go:build arm64\n\n// Code generated by quant_neon_gen.py; DO NOT EDIT.\n\n#include "textflag.h"\n')
e('// func quantQ8ActNEON(q *int8, s *float32, a *float32, nblocks int, c127, tiny float32)')
e('TEXT ·quantQ8ActNEON(SB), NOSPLIT, $0-40')
e('\tMOVD q+0(FP), R0\n\tMOVD s+8(FP), R1\n\tMOVD a+16(FP), R2\n\tMOVD nblocks+24(FP), R3\n\tFMOVS c127+32(FP), F28\n\tFMOVS tiny+36(FP), F29')
e('\tCBZ R3, done')
e('loop:')
e('\tVLD1.P 64(R2), [V0.S4, V1.S4, V2.S4, V3.S4]')
e('\tVLD1.P 64(R2), [V4.S4, V5.S4, V6.S4, V7.S4]')
for i in range(8): W(fabs(8+i,i),f'FABS V{8+i}, V{i}')
for i in range(4): W(fmax(8+i,8+i,12+i),'FMAX')
W(fmax(8,8,10),'FMAX');W(fmax(9,9,11),'FMAX');W(fmax(8,8,9),'FMAX')
W(fmaxv(16,8),'FMAXV S16, V8.4S')
e('\tFDIVS F28, F16, F17 // d = amax/127')
e('\tFMOVS.P F17, 4(R1)')
e('\tFMAXS F29, F16, F18 // max(amax, 1e-30)')
e('\tFDIVS F18, F28, F19 // id = 127/max')
for i in range(8):
    W(fmul_el0(i,i,19),f'FMUL V{i}, V{i}, V19.S[0]')
    W(fcvtns(i,i),f'FCVTNS V{i}')
for k in range(4):
    W(sqxtn_h(20+k,2*k),'SQXTN'); W(sqxtn2_h(20+k,2*k+1),'SQXTN2')
W(sqxtn_b(24,20),'SQXTN');W(sqxtn2_b(24,21),'SQXTN2')
W(sqxtn_b(25,22),'SQXTN');W(sqxtn2_b(25,23),'SQXTN2')
e('\tVST1.P [V24.B16, V25.B16], 32(R0)')
e('\tSUB $1, R3, R3\n\tCBNZ R3, loop')
e('done:\n\tRET')
open('quant_neon_arm64.s','w').write('\n'.join(L)+'\n')
