#!/usr/bin/env python3
"""Regenerate shaders_gen.go from the .comp sources in this directory.

The SPIR-V binaries are embedded as byte literals so the shipped Go binary has
no runtime dependency on glslang. Run this after editing any .comp file:

    python gen_shaders.py [path-to-glslang]

glslang is resolved from PATH, the Vulkan SDK, or an explicit argument.
"""
import os
import shutil
import struct
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), "shaders_gen.go")

# kernel name -> source file
SHADERS = [
    ("matmul", "matmul.comp"),
    ("rmsnorm_rows", "rmsnorm_rows.comp"),
    ("qk_norm_rope", "qk_norm_rope.comp"),
    ("attention", "attention.comp"),
    ("silu_mul", "silu_mul.comp"),
]


def find_glslang():
    if len(sys.argv) > 1:
        return sys.argv[1]
    for name in ("glslang", "glslangValidator"):
        p = shutil.which(name)
        if p:
            return p
    for env in ("VULKAN_SDK", "VK_SDK_PATH"):
        root = os.environ.get(env)
        if root:
            for name in ("glslang.exe", "glslangValidator.exe", "glslang", "glslangValidator"):
                p = os.path.join(root, "Bin", name)
                if os.path.exists(p):
                    return p
    return None


def compile_one(glslang, src, dst):
    cmd = [glslang, "-V", "--target-env", "vulkan1.1", "-o", dst, src]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit("glslang failed for %s:\n%s" % (src, r.stderr))
    # glslang warns on stderr for valid input; only a non-zero exit is fatal.


def main():
    glslang = find_glslang()
    if not glslang:
        sys.exit("glslang not found: pass its path as argv[1] or add it to PATH")
    blobs = []
    for name, fname in SHADERS:
        src = os.path.join(HERE, fname)
        tmp = os.path.join(HERE, ".%s.spv" % name)
        compile_one(glslang, src, tmp)
        with open(tmp, "rb") as f:
            data = f.read()
        os.remove(tmp)
        blobs.append((name, data))
        print("%-14s %6d bytes" % (name, len(data)))

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Code generated by gen_shaders.py; DO NOT EDIT.\n")
        f.write("//\n")
        f.write("// SPIR-V binaries for the Qwen3 Vulkan kernels. Regenerate with\n")
        f.write("// `python gen_shaders.py` after changing a .comp source.\n\n")
        f.write("package vk\n\n")
        f.write("// shaderSPIRV maps kernel name -> SPIR-V module bytes.\n")
        f.write("var shaderSPIRV = map[string][]byte{\n")
        for name, data in blobs:
            f.write('\t"%s": {\n' % name)
            for i in range(0, len(data), 16):
                chunk = data[i:i + 16]
                f.write("\t\t" + ", ".join("0x%02x" % b for b in chunk) + ",\n")
            f.write("\t},\n")
        f.write("}\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
