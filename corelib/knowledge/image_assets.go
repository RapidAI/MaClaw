// HasAssets checks if the source has any image assets stored.
func (m *ImageAssetManager) HasAssets(sourceID string) bool {
	dir, err := m.managedAssetDir(sourceID)
	if err != nil {
		return false
	}
	info, err := os.Lstat(dir)
	return err == nil && info.IsDir() && info.Mode()&os.ModeSymlink == 0
}

// RegenerateThumb regenerates a missing thumbnail from the original image.
func (m *ImageAssetManager) RegenerateThumb(sourceID string) error {
	dir, err := m.managedAssetDir(sourceID)
	if err != nil {
		return err
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		return fmt.Errorf("read asset dir: %w", err)
	}
	var originalPath string
	for _, e := range entries {
		if e.Type()&os.ModeSymlink == 0 && e.Type().IsRegular() && isOriginalRasterImageName(e.Name()) {
			originalPath = filepath.Join(dir, e.Name())
			break
		}
	}
	if originalPath == "" {
		return fmt.Errorf("original image not found in %s", dir)
	}

	f, err := os.Open(originalPath)
	if err != nil {
		return err
	}
	defer f.Close()
	if info, statErr := f.Stat(); statErr != nil {
		return fmt.Errorf("stat original: %w", statErr)
	} else if info.Size() > MaxKnowledgeImageAssetBytes {
		return imageAssetTooLargeError(info.Size())
	}
	if err := validateImageDimensions(f); err != nil {
		return fmt.Errorf("inspect original: %w", err)
	}
	if _, err := f.Seek(0, io.SeekStart); err != nil {
		return fmt.Errorf("rewind original: %w", err)
	}

	img, _, err := image.Decode(f)
	if err != nil {
		return fmt.Errorf("decode original: %w", err)
	}

	if err := saveScaledJPEG(img, filepath.Join(dir, "thumb_120.jpg"), ThumbSize, ThumbSize, true); err != nil {
		return fmt.Errorf("generate thumb: %w", err)
	}
	if err := saveScaledJPEG(img, filepath.Join(dir, "preview_480.jpg"), PreviewWidth, PreviewWidth, true); err != nil {
		return fmt.Errorf("generate preview: %w", err)
	}
	return nil
}

// ReadKnowledgeImageThumbnail reads a generated thumbnail through the same
// managed-asset boundary used by image viewers and HTTP handlers. It is for
// presentation code that has the asset root but must not construct a host path
// from an asset ID itself.
func ReadKnowledgeImageThumbnail(assetBaseDir, assetID string) ([]byte, error) {
	data, _, err := ReadKnowledgeImageAsset(assetBaseDir, assetID, "thumbnail")
	return data, err
}

// ReadKnowledgeImageAsset returns display-safe managed image bytes and their
// detected format without exposing a host path. Presentation layers use this
// after authorization so a local cache entry cannot be checked and then
// reopened by pathname after a concurrent replacement.
func ReadKnowledgeImageAsset(assetBaseDir, assetID, variant string) ([]byte, string, error) {
	dir, err := managedImageAssetDir(assetBaseDir, assetID)
	if err != nil {
		return nil, "", err
	}
	root, err := os.OpenRoot(dir)
	if err != nil {
		return nil, "", err
	}
	defer root.Close()

	variant = strings.ToLower(strings.TrimSpace(variant))
	if variant == "thumbnail" || variant == "preview" {
		name, maxEdge, maxBytes := "thumb_120.jpg", ThumbSize, MaxKnowledgeImageThumbnailBytes
		if variant == "preview" {
			name, maxEdge, maxBytes = "preview_480.jpg", PreviewWidth, MaxKnowledgeImagePreviewBytes
		}
		data, err := readManagedImageFile(root, name, maxBytes)
		if err != nil || !isSafeDerivedKnowledgeImage(data, maxEdge) {
			return nil, "", os.ErrNotExist
		}
		return data, "jpeg", nil
	}
	if variant != "original" {
		return nil, "", fmt.Errorf("invalid image variant")
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, "", err
	}
	for _, entry := range entries {
		if entry.Type()&os.ModeSymlink != 0 || !entry.Type().IsRegular() || !isOriginalRasterImageName(entry.Name()) {
			continue
		}
		data, err := readManagedImageFile(root, entry.Name(), MaxKnowledgeImageAssetBytes)
		if err != nil {
			continue
		}
		config, format, err := image.DecodeConfig(bytes.NewReader(data))
		if err != nil || !isSupportedImageFormat(format) || config.Width <= 0 || config.Height <= 0 || int64(config.Width) > MaxKnowledgeImageAssetPixels/int64(config.Height) {
			continue
		}
		return data, format, nil
	}
	return nil, "", os.ErrNotExist
}

func readManagedImageFile(root *os.Root, name string, maxBytes int64) ([]byte, error) {
	info, err := root.Lstat(name)
	if err != nil || !info.Mode().IsRegular() || info.Size() <= 0 || info.Size() > maxBytes {
		return nil, os.ErrNotExist
	}
	file, err := root.Open(name)
	if err != nil {
		return nil, os.ErrNotExist
	}
	defer file.Close()
	opened, statErr := file.Stat()
	if statErr != nil || !opened.Mode().IsRegular() || opened.Size() != info.Size() {
		return nil, os.ErrNotExist
	}
	data, err := io.ReadAll(io.LimitReader(file, maxBytes+1))
	if err != nil || int64(len(data)) != info.Size() || int64(len(data)) > maxBytes {
		return nil, os.ErrNotExist
	}
	return data, nil
}

func isSafeDerivedKnowledgeImage(data []byte, maxEdge int) bool {
	config, format, err := image.DecodeConfig(bytes.NewReader(data))
	return err == nil && format == "jpeg" && config.Width > 0 && config.Height > 0 && config.Width <= maxEdge && config.Height <= maxEdge
}

// managedAssetDir resolves an existing asset directory without following an
// asset-directory symlink. Assets are addressed by model-visible IDs, so a
// locally replaced cache entry must not turn an image preview into a read of
// an arbitrary host file.
func (m *ImageAssetManager) managedAssetDir(assetID string) (string, error) {
	if m == nil {
		return "", fmt.Errorf("image assets are not configured")
	}
	return managedImageAssetDir(m.baseDir, assetID)
}

func managedImageAssetDir(baseDir, assetID string) (string, error) {
	if !IsSafeImageAssetID(assetID) {
		return "", fmt.Errorf("invalid image asset ID")
	}
	baseDir = filepath.Clean(strings.TrimSpace(baseDir))
	if baseDir == "." || baseDir == "" {
		return "", fmt.Errorf("invalid image asset base directory")
	}
	resolvedBase, err := filepath.EvalSymlinks(baseDir)
	if err != nil {
		return "", err
	}
	assetDir := filepath.Join(resolvedBase, assetID)
	info, err := os.Lstat(assetDir)
	if err != nil || !info.IsDir() || info.Mode()&os.ModeSymlink != 0 {
		return "", os.ErrNotExist
	}
	resolvedAsset, err := filepath.EvalSymlinks(assetDir)
	if err != nil {
		return "", err
	}
	rel, err := filepath.Rel(resolvedBase, resolvedAsset)
	if err != nil || rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator)) || filepath.IsAbs(rel) {
		return "", fmt.Errorf("image asset is outside managed directory")
	}
	return resolvedAsset, nil
}

// --- internal ---

type bytesReader struct {
	data []byte
	pos  int
}

func (b *bytesReader) Read(p []byte) (int, error) {
	if b.pos >= len(b.data) {
		return 0, io.EOF
	}
	n := copy(p, b.data[b.pos:])
	b.pos += n
	return n, nil
}

func (m *ImageAssetManager) saveImageFromReader(sourceID string, r io.Reader, ext string, sizeBytes int64) (*ImageAsset, error) {
	if sizeBytes > MaxKnowledgeImageAssetBytes {
		return nil, imageAssetTooLargeError(sizeBytes)
	}
	dir := m.AssetDir(sourceID)
	if dir == "" {
		return nil, fmt.Errorf("invalid source ID: contains path traversal characters")
	}
	if err := os.MkdirAll(m.baseDir, 0o755); err != nil {
		return nil, fmt.Errorf("create asset base dir: %w", err)
	}
	tempDir, err := os.MkdirTemp(m.baseDir, ".image-asset-")
	if err != nil {
		return nil, fmt.Errorf("create temporary asset dir: %w", err)
	}
	published := false
	defer func() {
		if !published {
			_ = os.RemoveAll(tempDir)
		}
	}()

	ext = normalizeImageExt(ext)

	// Build the replacement asset away from the published directory. A failed
	// save must not leave partial files or overwrite the current asset.
	tempOriginalPath := filepath.Join(tempDir, "original"+ext)
	outFile, err := os.Create(tempOriginalPath)
	if err != nil {
		return nil, fmt.Errorf("create original: %w", err)
	}

	written, err := io.Copy(outFile, io.LimitReader(r, MaxKnowledgeImageAssetBytes+1))
	if err != nil {
		outFile.Close()
		return nil, fmt.Errorf("write original: %w", err)
	}
	if err := outFile.Close(); err != nil {
		return nil, fmt.Errorf("close original: %w", err)
	}
	if written > MaxKnowledgeImageAssetBytes {
		return nil, imageAssetTooLargeError(written)
	}

	// The copied size is authoritative: the source may have changed after Stat.
	sizeBytes = written

	imgFile, err := os.Open(tempOriginalPath)
	if err != nil {
		return nil, fmt.Errorf("reopen original: %w", err)
	}
	defer imgFile.Close()
	if err := validateImageDimensions(imgFile); err != nil {
		return nil, fmt.Errorf("inspect image: %w", err)
	}
	if _, err := imgFile.Seek(0, io.SeekStart); err != nil {
		return nil, fmt.Errorf("rewind image: %w", err)
	}

	img, format, err := image.Decode(imgFile)
	if closeErr := imgFile.Close(); closeErr != nil {
		return nil, fmt.Errorf("close inspected image: %w", closeErr)
	}
	if err != nil {
		// Image cannot be decoded (e.g. SVG, EMF, WMF) — retain the supported
		// original-only behavior, but still publish atomically.
		asset := &ImageAsset{
			OriginalPath: filepath.Join(dir, "original"+ext),
			Format:       strings.TrimPrefix(ext, "."),
			SizeBytes:    sizeBytes,
		}
		if err := publishImageAssetDir(dir, tempDir); err != nil {
			return nil, err
		}
		published = true
		return asset, nil
	}

	bounds := img.Bounds()
	asset := &ImageAsset{
		OriginalPath: filepath.Join(dir, "original"+ext),
		Width:        bounds.Dx(),
		Height:       bounds.Dy(),
		Format:       format,
		SizeBytes:    sizeBytes,
	}

	// Generate thumbnail (120x120, fit within square).
	tempThumbPath := filepath.Join(tempDir, "thumb_120.jpg")
	if err := saveScaledJPEG(img, tempThumbPath, ThumbSize, ThumbSize, true); err == nil {
		asset.ThumbPath = filepath.Join(dir, "thumb_120.jpg")
	}

	// Generate preview (fit within a 480px square).
	tempPreviewPath := filepath.Join(tempDir, "preview_480.jpg")
	if err := saveScaledJPEG(img, tempPreviewPath, PreviewWidth, PreviewWidth, true); err == nil {
		asset.PreviewPath = filepath.Join(dir, "preview_480.jpg")
	}

	if err := publishImageAssetDir(dir, tempDir); err != nil {
		return nil, err
	}
	published = true
	return asset, nil
}

// publishImageAssetDir swaps a complete staged asset into place. Should the
// final rename fail, the previous asset is restored before returning an error.
func publishImageAssetDir(dir, tempDir string) error {
	backupDir := imageAssetBackupDir(dir)
	if err := os.RemoveAll(backupDir); err != nil {
		return fmt.Errorf("clear prior asset backup: %w", err)
	}
	if err := os.Rename(dir, backupDir); err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("stage prior asset: %w", err)
	}
	if err := os.Rename(tempDir, dir); err != nil {
		if restoreErr := os.Rename(backupDir, dir); restoreErr != nil && !os.IsNotExist(restoreErr) {
			return fmt.Errorf("publish image asset: %w (restore prior asset: %v)", err, restoreErr)
		}
		return fmt.Errorf("publish image asset: %w", err)
	}
	// The new asset is already published. A locked old file (common on Windows)
	// must not turn a successful import into an error or cause a later writer to
	// discard the just-published directory. Leave the stale backup for the next
	// successful replacement or normal source cleanup to reclaim.
	if err := os.RemoveAll(backupDir); err != nil && !os.IsNotExist(err) {
		return nil
	}
	return nil
}

func imageAssetBackupDir(dir string) string {
	return dir + ".previous"
}

// validateImageDimensions rejects images whose decoded pixel area would
// exceed the resource budget before image.Decode allocates their full raster.
// Unsupported/vector formats are retained as originals and therefore do not
// need a raster-dimension check here.
func validateImageDimensions(r io.Reader) error {
	config, _, err := image.DecodeConfig(r)
	if err != nil {
		if config.Width > 0 && config.Height > 0 && int64(config.Width) > MaxKnowledgeImageAssetPixels/int64(config.Height) {
			return fmt.Errorf("image dimensions exceed %d pixels", MaxKnowledgeImageAssetPixels)
		}
		return nil
	}
	if config.Width <= 0 || config.Height <= 0 {
		return fmt.Errorf("invalid image dimensions")
	}
	if int64(config.Width) > MaxKnowledgeImageAssetPixels/int64(config.Height) {
		return fmt.Errorf("image dimensions exceed %d pixels", MaxKnowledgeImageAssetPixels)
	}
	return nil
}

// saveScaledJPEG scales the image to fit within maxW x maxH and saves as JPEG.
// If fitSquare is true, both dimensions are capped. If fitSquare is false and
// maxH is 0, height is computed proportionally from maxW.
func saveScaledJPEG(src image.Image, dstPath string, maxW, maxH int, fitSquare bool) error {
	bounds := src.Bounds()
	srcW := bounds.Dx()
	srcH := bounds.Dy()

	if srcW == 0 || srcH == 0 {
		return fmt.Errorf("zero-dimension image")
	}

	var dstW, dstH int
	if fitSquare {
		// Fit within maxW x maxH square, maintaining aspect ratio.
		ratio := float64(srcW) / float64(srcH)
		if ratio > 1 {
			// Landscape
			dstW = maxW
			dstH = int(float64(maxW) / ratio)
		} else {
			// Portrait or square
			dstH = maxH
			dstW = int(float64(maxH) * ratio)
		}
	} else {
		// Scale to maxW, proportional height.
		if srcW <= maxW {
			// Already smaller — don't upscale.
			dstW = srcW
			dstH = srcH
		} else {
			dstW = maxW
			dstH = int(float64(srcH) * float64(maxW) / float64(srcW))
		}
	}

	if dstW <= 0 {
		dstW = 1
	}
	if dstH <= 0 {
		dstH = 1
	}

	dst := image.NewRGBA(image.Rect(0, 0, dstW, dstH))
	draw.BiLinear.Scale(dst, dst.Bounds(), src, bounds, draw.Over, nil)

	f, err := os.Create(dstPath)
	if err != nil {
		return err
	}
	defer f.Close()

	return jpeg.Encode(f, dst, &jpeg.Options{Quality: 80})
}

// normalizeImageExt ensures the extension has a dot and is lowercase.
func normalizeImageExt(ext string) string {
	ext = strings.ToLower(strings.TrimSpace(ext))
	if ext == "" {
		return ".png"
	}
	if !strings.HasPrefix(ext, ".") {
		ext = "." + ext
	}
	// Normalize common variants.
	switch ext {
	case ".jpeg":
		return ".jpg"
	default:
		return ext
	}
}

// IsImageExt returns true if the file extension is a supported image format.
func IsImageExt(ext string) bool {
	ext = strings.ToLower(strings.TrimSpace(ext))
	if !strings.HasPrefix(ext, ".") {
		ext = "." + ext
	}
	for _, e := range ImageIncludeExts {
		if ext == e {
			return true
		}
	}
	return false
}

func isOriginalRasterImageName(name string) bool {
	ext := strings.ToLower(filepath.Ext(name))
	return ext != "" && name == "original"+ext && IsImageExt(ext)
}

func isSupportedImageFormat(format string) bool {
	switch strings.ToLower(format) {
	case "png", "jpeg", "gif", "webp", "bmp":
		return true
	default:
		return false
	}
}

// IsVectorImageExt returns true for vector image formats that cannot be OCR'd.
func IsVectorImageExt(ext string) bool {
	ext = strings.ToLower(strings.TrimSpace(ext))
	switch ext {
	case ".emf", ".wmf", ".svg":
		return true
	}
	return false
}
