const (
	// ThumbSize is the max edge length for list thumbnails.
	ThumbSize = 120
	// PreviewWidth is the max edge length for detail preview images. Keeping
	// both dimensions bounded prevents a narrow-but-very-tall source image from
	// creating an unexpectedly large preview raster.
	PreviewWidth = 480
	// MaxKnowledgeImageThumbnailBytes and MaxKnowledgeImagePreviewBytes bound
	// derived JPEG files before presentation layers inspect or serve them. They
	// protect against a locally corrupted asset cache being advertised as a
	// small generated image.
	MaxKnowledgeImageThumbnailBytes int64 = 256 * 1024
	MaxKnowledgeImagePreviewBytes   int64 = 2 * 1024 * 1024
	// MaxKnowledgeImageAssetBytes is the largest original image accepted by the
	// managed knowledge asset store. Every ingestion path (standalone files,
	// Office documents and PDFs) goes through this boundary.
	MaxKnowledgeImageAssetBytes int64 = 20 * 1024 * 1024
	// MaxKnowledgeImageAssetPixels bounds decoded image area before decoding or
	// resizing so compressed image bombs cannot cause unbounded allocations.
	MaxKnowledgeImageAssetPixels int64 = 40 * 1024 * 1024

	imageAssetsSubdir = "knowledge_assets"
)

var errKnowledgeImageAssetTooLarge = errors.New("knowledge image asset exceeds size limit")

// Image asset IDs are opaque identifiers generated by the knowledge store.
// Keep the grammar deliberately narrow because an asset ID is also used as a
// directory name by every desktop and HTTP consumer.
var safeImageAssetIDPattern = regexp.MustCompile(`^[A-Za-z0-9_-]{1,200}$`)

// IsSafeImageAssetID reports whether value can safely identify a managed
// knowledge image asset. Callers that receive an ID across a model, HTTP, or
// WebView boundary must validate it before looking up an asset.
func IsSafeImageAssetID(value string) bool {
	// Asset IDs cross model, HTTP, and WebView boundaries. Do not normalize
	// them during validation: accepting surrounding whitespace here while some
	// callers later use the original value would make one external token name a
	// different on-disk asset. Each presentation boundary must either reject the
	// token or explicitly canonicalize it before both validation and lookup.
	return safeImageAssetIDPattern.MatchString(value)
}

func imageAssetTooLargeError(size int64) error {
	return fmt.Errorf("%w (%d bytes)", errKnowledgeImageAssetTooLarge, size)
}

// ImageAsset holds paths and metadata for a stored image asset.
type ImageAsset struct {
	OriginalPath string // absolute path to original image
	ThumbPath    string // absolute path to 120px thumbnail
	PreviewPath  string // absolute path to 480px preview
	Width        int    // original image width in pixels
	Height       int    // original image height in pixels
	Format       string // detected format: "png", "jpeg", "gif", "bmp", "webp"
	SizeBytes    int64  // original file size
}

// ImageAssetManager manages image asset storage and lifecycle.
type ImageAssetManager struct {
	baseDir string // ~/.maclaw/knowledge_assets/
}

// NewImageAssetManager creates a manager rooted at the given base directory.
// The directory is created if it does not exist.
func NewImageAssetManager(maclawDataDir string) (*ImageAssetManager, error) {
	baseDir := filepath.Join(maclawDataDir, imageAssetsSubdir)
	if err := os.MkdirAll(baseDir, 0o755); err != nil {
		return nil, fmt.Errorf("knowledge image_assets: create base dir: %w", err)
	}
	return &ImageAssetManager{baseDir: baseDir}, nil
}

// BaseDir returns the absolute base directory for image assets.
func (m *ImageAssetManager) BaseDir() string {
	return m.baseDir
}

// SaveImageFromPath saves an image file and generates thumbnails.
// sourceID is used as the subdirectory name.
// Returns the asset metadata or an error.
func (m *ImageAssetManager) SaveImageFromPath(sourceID, imagePath string) (*ImageAsset, error) {
	f, err := os.Open(imagePath)
	if err != nil {
		return nil, fmt.Errorf("open image: %w", err)
	}
	defer f.Close()

	info, err := f.Stat()
	if err != nil {
		return nil, fmt.Errorf("stat image: %w", err)
	}
	if info.Size() > MaxKnowledgeImageAssetBytes {
		return nil, imageAssetTooLargeError(info.Size())
	}

	return m.saveImageFromReader(sourceID, f, filepath.Ext(imagePath), info.Size())
}

// SaveImageFromBytes saves raw image bytes and generates thumbnails.
// ext should include the dot (e.g. ".png", ".jpg").
func (m *ImageAssetManager) SaveImageFromBytes(sourceID string, data []byte, ext string) (*ImageAsset, error) {
	if int64(len(data)) > MaxKnowledgeImageAssetBytes {
		return nil, imageAssetTooLargeError(int64(len(data)))
	}
	r := &bytesReader{data: data}
	return m.saveImageFromReader(sourceID, r, ext, int64(len(data)))
}

// DeleteAssets removes the standalone image asset directory for an exact asset
// ID. It intentionally does not remove embedded-image assets, whose IDs are
// derived from the owning source ID with an underscore suffix.
// Returns nil if sourceID is invalid or directory doesn't exist.
func (m *ImageAssetManager) DeleteAssets(sourceID string) error {
	dir := m.AssetDir(sourceID)
	if dir == "" {
		return nil // invalid sourceID, nothing to delete
	}
	if err := os.RemoveAll(dir); err != nil {
		return err
	}
	return os.RemoveAll(imageAssetBackupDir(dir))
}

// DeleteAssetsForSource removes a source's standalone asset plus the exact
// embedded asset IDs recorded for that source. Embedded assets are deliberately
// supplied by the database caller rather than discovered by directory prefix:
// another valid source ID could otherwise happen to begin with sourceID+"_".
func (m *ImageAssetManager) DeleteAssetsForSource(sourceID string, embeddedAssetIDs ...string) error {
	if m == nil || m.AssetDir(sourceID) == "" {
		return nil
	}
	ids := append([]string{sourceID}, embeddedAssetIDs...)
	seen := make(map[string]struct{}, len(ids))
	prefix := sourceID + "_"
	for _, assetID := range ids {
		if !IsSafeImageAssetID(assetID) || (assetID != sourceID && !strings.HasPrefix(assetID, prefix)) {
			continue
		}
		if _, ok := seen[assetID]; ok {
			continue
		}
		seen[assetID] = struct{}{}
		dir := m.AssetDir(assetID)
		if dir == "" {
			continue
		}
		if err := os.RemoveAll(dir); err != nil {
			return err
		}
		if err := os.RemoveAll(imageAssetBackupDir(dir)); err != nil {
			return err
		}
	}
	return nil
}

// AssetDir returns the absolute directory path for a source's assets.
// Returns empty string if sourceID contains path traversal characters.
func (m *ImageAssetManager) AssetDir(sourceID string) string {
	if !IsSafeImageAssetID(sourceID) {
		return ""
	}
	return filepath.Join(m.baseDir, sourceID)
}

// OriginalPath returns the expected original image path for a source.
func (m *ImageAssetManager) OriginalPath(sourceID, ext string) string {
	dir := m.AssetDir(sourceID)
	if dir == "" {
		return ""
	}
	return filepath.Join(dir, "original"+ext)
}

// OriginalImage resolves the retained original only when it is a bounded,
// decodable raster image. Asset directories can contain original-only vector
// resources extracted from Office documents; those must not be passed to a
// browser or system viewer through an image-display API.
func (m *ImageAssetManager) OriginalImage(assetID string) (string, string, error) {
	dir, err := m.managedAssetDir(assetID)
	if err != nil {
		return "", "", err
	}
	root, err := os.OpenRoot(dir)
	if err != nil {
		return "", "", err
	}
	defer root.Close()
	entries, err := os.ReadDir(dir)
	if err != nil {
		return "", "", err
	}
	for _, entry := range entries {
		if entry.Type()&os.ModeSymlink != 0 || !entry.Type().IsRegular() || !isOriginalRasterImageName(entry.Name()) {
			continue
		}
		info, err := root.Lstat(entry.Name())
		if err != nil || !info.Mode().IsRegular() || info.Size() <= 0 || info.Size() > MaxKnowledgeImageAssetBytes {
			continue
		}
		file, err := root.Open(entry.Name())
		if err != nil {
			continue
		}
		opened, statErr := file.Stat()
		if statErr != nil || !opened.Mode().IsRegular() || opened.Size() != info.Size() {
			_ = file.Close()
			continue
		}
		config, format, decodeErr := image.DecodeConfig(file)
		closeErr := file.Close()
		if decodeErr != nil || closeErr != nil || !isSupportedImageFormat(format) || config.Width <= 0 || config.Height <= 0 || int64(config.Width) > MaxKnowledgeImageAssetPixels/int64(config.Height) {
			continue
		}
		return filepath.Join(dir, entry.Name()), format, nil
	}
	return "", "", os.ErrNotExist
}

// OriginalImagePath is the path-only convenience form of OriginalImage.
func (m *ImageAssetManager) OriginalImagePath(assetID string) (string, error) {
	path, _, err := m.OriginalImage(assetID)
	return path, err
}

// DerivedImage resolves a generated thumbnail or preview only when it remains
// within the managed JPEG contract. Consumers use this rather than serving a
// predictable cache filename directly, because derived files can outlive a
// failed write or be externally corrupted on a shared local data volume.
func (m *ImageAssetManager) DerivedImage(assetID, variant string) (string, error) {
	var name string
	var maxEdge int
	var maxBytes int64
	switch strings.ToLower(strings.TrimSpace(variant)) {
	case "thumbnail":
		name = "thumb_120.jpg"
		maxEdge = ThumbSize
		maxBytes = MaxKnowledgeImageThumbnailBytes
	case "preview":
		name = "preview_480.jpg"
		maxEdge = PreviewWidth
		maxBytes = MaxKnowledgeImagePreviewBytes
	default:
		return "", fmt.Errorf("invalid image variant")
	}
	dir, err := m.managedAssetDir(assetID)
	if err != nil {
		return "", err
	}
	root, err := os.OpenRoot(dir)
	if err != nil {
		return "", err
	}
	defer root.Close()
	path := filepath.Join(dir, name)
	info, err := root.Lstat(name)
	if err != nil || !info.Mode().IsRegular() || info.Size() <= 0 || info.Size() > maxBytes {
		return "", os.ErrNotExist
	}
	file, err := root.Open(name)
	if err != nil {
		return "", err
	}
	opened, statErr := file.Stat()
	if statErr != nil || !opened.Mode().IsRegular() || opened.Size() != info.Size() {
		_ = file.Close()
		return "", os.ErrNotExist
	}
	config, format, decodeErr := image.DecodeConfig(file)
	closeErr := file.Close()
	if decodeErr != nil || closeErr != nil || format != "jpeg" || config.Width <= 0 || config.Height <= 0 || config.Width > maxEdge || config.Height > maxEdge {
		return "", os.ErrNotExist
	}
	return path, nil
}

