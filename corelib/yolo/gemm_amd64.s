// AVX2+FMA register-blocked GEMM tile kernel for the YOLO conv path.
//
// The kernel computes a C[6][16] tile:
//
//	C[m][n] = sum_k A[m][k] * B[k][n0+n] + bias[m]
//
// A is [M,K] row-major, B is [K,N] row-major (the caller passes &col[n0]),
// C is [M,N] row-major (the caller passes &out[m0*N+n0]). ldb/ldc are the
// row strides of B and C in elements. The k loop streams 16 B columns with
// unit stride, so no im2col transpose is ever needed.
//
// silu selects a fused SiLU epilogue (x * sigmoid(x), vectorized cephes exp
// + Newton-refined reciprocal) applied on accumulators before the store;
// without it the accumulators are stored as-is.
//
// Register use: Y0-Y11 accumulators (row r halves: Y(2r), Y(2r+1)),
// Y12/Y13 B vectors, Y14 A broadcast, Y15 scratch. GP: DI,R12,R13,R14,R15,BP
// A row pointers, SI B pointer, R9 ldb*4, R11 k*4 index, CX pair counter,
// DX k parity, AX silu flag, R8/R10 C pointer/ldc*4 in the epilogue.

DATA yoloExpConsts<>+0(SB)/4, $0x80000000 // signMask
DATA yoloExpConsts<>+4(SB)/4, $0xc2b0c0a5 // expMin = -88.37626
