	VMOVAPS Y14, Y8
	VMOVAPS Y14, Y9
	VBROADCASTSS 20(BX), Y14
	VMOVAPS Y14, Y10
	VMOVAPS Y14, Y11

	TESTQ CX, CX
	JZ    g6tail

